type generatorBase struct {
	outputBaseDir  string
	generatedFiles map[generatedFileKey]*generatedFile
	errors         []error

	// nonAutogeneratedCache memoizes scanNonAutogeneratedTypes per source directory.
	nonAutogeneratedCache map[string]*nonAutogeneratedTypes

	// onlyUsedImports filters imports written to generated files so that only packages
	// referenced in the rendered file body are emitted, while also ensuring required
	// qualifier imports are included.
	onlyUsedImports bool
}

func (g *generatorBase) init(outputBaseDir string) {
	g.outputBaseDir = outputBaseDir
	g.generatedFiles = make(map[generatedFileKey]*generatedFile)
	g.nonAutogeneratedCache = make(map[string]*nonAutogeneratedTypes)
}

// nonAutogeneratedTypes tracks type names and proto annotations declared in non-autogenerated
// files within the target package, preventing conflicting declarations or orphaned ObservedState structs.
type nonAutogeneratedTypes struct {
	// typeNames contains all Go type names declared in non-autogenerated files.
	typeNames map[string]bool
	// protoTagged contains all protobuf message full names associated with +kcc:*proto annotations
	// in non-autogenerated files.
	protoTagged map[string]bool
}

// ownedByGenerator reports whether a proto message is safely manageable by the generator,
// verifying that neither its proto name nor its generated Go type names (base or ObservedState)
// collide with existing non-autogenerated declarations in the package.
func (h *nonAutogeneratedTypes) ownedByGenerator(protoFullName string, goName string, observedStateGoName string) bool {
	if h == nil {
		return true
	}
	return !h.protoTagged[protoFullName] && !h.typeNames[goName] && !h.typeNames[observedStateGoName]
}

// scanNonAutogeneratedTypes scans non-autogenerated Go files in srcDir and records their type declarations
// and proto annotations, caching the result per directory. A missing directory is not an error:
// a service generated for the first time does not have one yet.
func (g *generatorBase) scanNonAutogeneratedTypes(srcDir string) (*nonAutogeneratedTypes, error) {
	if cached, ok := g.nonAutogeneratedCache[srcDir]; ok {
		return cached, nil
	}

	out := &nonAutogeneratedTypes{
		typeNames:   make(map[string]bool),
		protoTagged: make(map[string]bool),
	}

	files, err := os.ReadDir(srcDir)
	if err != nil {
		if os.IsNotExist(err) {
			g.nonAutogeneratedCache[srcDir] = out
			return out, nil
		}
		return nil, fmt.Errorf("reading directory %q: %w", srcDir, err)
	}

	for _, f := range files {
		p := filepath.Join(srcDir, f.Name())
		if !strings.HasSuffix(p, ".go") || strings.HasSuffix(p, "generated.go") {
			continue
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return nil, fmt.Errorf("reading file %q: %w", p, err)
		}
		protoLines := make(map[string]string)
		scanFileDeclarations(string(b), out.typeNames, protoLines)
		for protoMessage := range protoLines {
			out.protoTagged[protoMessage] = true
		}
	}

	g.nonAutogeneratedCache[srcDir] = out
	return out, nil
}

type protoTagComment struct {
	protoMessage   string
	annotationKind string
	line           string
}

// scanFileDeclarations records Go type declarations into typeNames (if non-nil) and
// non-forked +kcc:*proto annotations into protoTagged (mapping protoFullName to the raw line).
// Hand-authored variant structs whose Go type name differs from the proto message's base Go name
// co-exist alongside the generator's base struct and do not claim ownership in protoTagged.
func scanFileDeclarations(content string, typeNames map[string]bool, protoTagged map[string]string) {
	var pending []protoTagComment
	for _, raw := range strings.Split(content, "\n") {
		trimmed := strings.TrimSpace(raw)
		if protoMessage, annotationKind, ok := GetProtoMessageAndKindFromAnnotation(trimmed); ok {
			pending = append(pending, protoTagComment{
				protoMessage:   protoMessage,
				annotationKind: annotationKind,
				line:           raw,
			})
			continue
		}
		if name, ok := goTypeNameFromDeclaration(trimmed); ok {
			if typeNames != nil {
				typeNames[name] = true
			}
			for _, p := range pending {
				if p.annotationKind != KCCProtoMessageAnnotationMisc || isBaseProtoStructName(name, p.protoMessage) {
					protoTagged[p.protoMessage] = p.line
				}
			}
			pending = nil
			continue
		}
		if trimmed != "" && !strings.HasPrefix(trimmed, "//") {
			for _, p := range pending {
				protoTagged[p.protoMessage] = p.line
			}
			pending = nil
		}
	}
	for _, p := range pending {
		protoTagged[p.protoMessage] = p.line
	}
}

// isBaseProtoStructName reports whether typeName is the default (non-forked) Go
// struct name for protoFullName (for example "FunctionDeclaration" for
// "google.cloud.test.v1.FunctionDeclaration", "PSCConfig" for "...PscConfig",
// or "Parent_Child" for "...Parent.Child").
func isBaseProtoStructName(typeName, protoFullName string) bool {
	normalizedType := strings.ToLower(strings.ReplaceAll(typeName, "_", "."))
	normalizedProto := "." + strings.ToLower(protoFullName)
	return strings.HasSuffix(normalizedProto, "."+normalizedType)
}

// goTypeNameFromDeclaration extracts the type name from a "type <Name> ..." declaration line.
func goTypeNameFromDeclaration(line string) (string, bool) {
	rest, ok := strings.CutPrefix(line, "type ")
	if !ok {
		return "", false
	}
	name, _, ok := strings.Cut(rest, " ")
	if !ok || name == "" {
		return "", false
	}
	return name, true
}

func (g *generatorBase) getOutputFile(k generatedFileKey) *generatedFile {
	out := g.generatedFiles[k]
	if out == nil {
		out = &generatedFile{key: k, baseDir: g.outputBaseDir}
		g.generatedFiles[k] = out
	}
	return out
}

func (g *generatorBase) Errorf(msg string, args ...any) {
	g.errors = append(g.errors, fmt.Errorf(msg, args...))
}

type generatedFile struct {
	baseDir   string
	key       generatedFileKey
	goPackage string
	body      bytes.Buffer

	fileAnnotation *annotations.FileAnnotation

	imports map[string]string

	// reservedTypeNames holds Go type names that will be declared by the scaffolder
	// in non-generated files, so they should not be preserved from an existing
	// types.generated.go file.
	reservedTypeNames map[string]bool

	// validKRMTypes holds active KRM struct names in the target API packages when
	// generating mappers; existing mapper functions for deleted or pruned KRM types
	// are not preserved.
	validKRMTypes map[string]bool
}

type generatedFileKey struct {
	GoPackage string

	FileName string
}

func (f *generatedFile) OutputDir() string {
	tokens := strings.Split(f.key.GoPackage, ".")
	dirTokens := []string{f.baseDir}
	dirTokens = append(dirTokens, tokens...)
	dir := filepath.Join(dirTokens...)
	return dir
}

func (f *generatedFile) addImport(alias string, pkgName string) {
	if f.imports == nil {
		f.imports = make(map[string]string)
	}
	f.imports[pkgName] = alias
}

func (f *generatedFile) Write(addCopyright bool, writeEmptyFiles bool, onlyUsedImports bool) error {
	dir := f.OutputDir()
	p := filepath.Join(dir, f.key.FileName)

	existingBytes, err := os.ReadFile(p)
	if err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("reading existing file %q: %w", p, err)
	}
	if len(existingBytes) > 0 {
		f.mergeWithExisting(existingBytes, dir)
	}

	if f.body.Len() == 0 && !writeEmptyFiles {
		return nil
	}

	if err := os.MkdirAll(dir, 0755); err != nil {
		return fmt.Errorf("creating directory %q: %w", dir, err)
	}

	var w bytes.Buffer

	if addCopyright {
		year := time.Now().Year()
		if existingCopyrightYear, ok := extractCopyrightYear(existingBytes); ok {
			year = existingCopyrightYear
		}
		writeCopyright(&w, year)
	}

	fmt.Fprintf(&w, "// Code generated by dev/tasks/generate-all. DO NOT EDIT.\n")

	if f.key.FileName == "mapper.generated.go" {
		fmt.Fprintf(&w, "//go:build !ignore_autogenerated\n")
		fmt.Fprintf(&w, "// +build !ignore_autogenerated\n\n")
	}

	if f.fileAnnotation != nil {
		s := f.fileAnnotation.FormatGo()
		fmt.Fprintf(&w, "%s\n", s)
	}

	if f.goPackage != "" {
		fmt.Fprintf(&w, "package %s\n", f.goPackage)
		fmt.Fprintf(&w, "\n")
	}

	// Filter imports to only those referenced in the generated body when onlyUsedImports
	// is set, preventing unused import compilation errors for skipped types.
	used := f.imports
	if onlyUsedImports {
		used = f.usedImports()
	}
	if len(used) != 0 {
		w.WriteString("import (\n")
		for pkgName, alias := range used {
			if alias == "" {
				w.WriteString(fmt.Sprintf("\t%q\n", pkgName))
			} else {
				w.WriteString(fmt.Sprintf("\t%s %q\n", alias, pkgName))
			}
		}
		w.WriteString(")\n")
	}
	f.body.WriteTo(&w)

	formatted, err := imports.Process(p, w.Bytes(), nil)
	if err != nil {
		klog.Errorf("error from goimports processing file %q:\n%s", p, w.String())
		return fmt.Errorf("running goimports on %q: %w", p, err)
	}

	klog.V(2).Infof("writing file %v", p)
	if err := os.WriteFile(p, formatted, 0644); err != nil {
		return fmt.Errorf("writing %q: %w", p, err)
	}

	return nil
}

type generatedBlock struct {
	name            string
	kind            string // "type" or "func"
	isCommented     bool
	protoFQN        string
	isObservedState bool
	krmTypeName     string
	rawText         string
	offset          int
}

// mergeWithExisting merges declarations, imports, and FileAnnotation attributes from an
// existing generated Go file on disk into f so sequential generate-types or generate-mapper
// invocations (for example across multiple --service packages) accumulate additively.
func (f *generatedFile) mergeWithExisting(existingBytes []byte, dir string) {
	var matchingExistingAnn *annotations.FileAnnotation
	if f.fileAnnotation != nil {
		if existingAnns, err := annotations.FindFileAnnotations(existingBytes, []string{"+generated:"}); err == nil && len(existingAnns) > 0 {
			for i := range existingAnns {
				if existingAnns[i].Key == f.fileAnnotation.Key {
					eg := existingAnns[i].Attributes["krm.group"]
					cg := f.fileAnnotation.Attributes["krm.group"]
					if len(eg) > 0 && len(cg) > 0 && eg[0] != cg[0] {
						return
					}
					annCopy := existingAnns[i]
					matchingExistingAnn = &annCopy
					break
				}
			}
		}
	}

	if f.key.FileName == "types.generated.go" && isTargetOfSeparateGeneratedFile(dir, f.key.FileName, f.fileAnnotation) {
		return
	}

	pkgName := f.goPackage
	if pkgName == "" {
		pkgName = "p"
	}
	existingBlocks, existingImports, err := parseGeneratedGoBlocks(existingBytes, pkgName, false)
	if err != nil || len(existingBlocks) == 0 {
		return
	}
	currentBlocks, _, err := parseGeneratedGoBlocks(f.body.Bytes(), pkgName, true)
	if err != nil {
		return
	}

	if f.key.FileName == "mapper.generated.go" && len(currentBlocks) > 0 {
		if hasVersionedMapperFuncs(existingBlocks) != hasVersionedMapperFuncs(currentBlocks) {
			return
		}
	}

	currentByName := make(map[string]generatedBlock, len(currentBlocks))
	for _, b := range currentBlocks {
		if b.name != "" {
			currentByName[b.name] = b
		}
	}

	handwrittenTypes, handwrittenProtoTags, handwrittenFuncs := scanHandwrittenDirDeclarations(dir, f.key.FileName)

	validKRMTypes := f.validKRMTypes
	if validKRMTypes == nil && f.key.FileName == "mapper.generated.go" && f.baseDir != "" {
		validKRMTypes = discoverValidKRMTypes(f.baseDir, f.imports, existingImports)
	}

	var filteredExisting []generatedBlock
	hasActiveExternalBlocks := false
	for _, eb := range existingBlocks {
		if eb.name == "" {
			continue
		}
		if cb, inCurrent := currentByName[eb.name]; inCurrent && shouldCurrentReplaceExisting(eb, cb) {
			filteredExisting = append(filteredExisting, eb)
			continue
		}
		if eb.kind == "type" {
			if !eb.isCommented {
				if handwrittenTypes[eb.name] || f.reservedTypeNames[eb.name] {
					continue
				}
				if eb.protoFQN != "" && handwrittenProtoTags[eb.protoFQN] {
					baseName := strings.TrimSuffix(eb.name, "ObservedState")
					if isBaseProtoStructName(eb.name, eb.protoFQN) || isBaseProtoStructName(baseName, eb.protoFQN) {
						continue
					}
				}
			}
		} else if eb.kind == "func" {
			if !eb.isCommented && handwrittenFuncs[eb.name] {
				continue
			}
			if validKRMTypes != nil && eb.krmTypeName != "" && !validKRMTypes[eb.krmTypeName] {
				continue
			}
		}
		if !eb.isCommented {
			hasActiveExternalBlocks = true
		}
		filteredExisting = append(filteredExisting, eb)
	}

	if !hasActiveExternalBlocks {
		return
	}

	if matchingExistingAnn != nil && f.fileAnnotation != nil {
		f.fileAnnotation = mergeFileAnnotations(matchingExistingAnn, f.fileAnnotation)
	}

	// Merge imports from the existing file. If an existing import alias collides with
	// a different package in f.imports (or the same package uses a different alias),
	// assign a disambiguated alias and rewrite selector prefixes in filteredExisting blocks.
	usedAliases := make(map[string]string)
	for pkg, alias := range f.imports {
		qual := alias
		if qual == "" {
			qual = lastGoComponent(pkg)
		}
		if qual != "" {
			usedAliases[qual] = pkg
		}
	}
	aliasRenames := make(map[string]string)
	existingPkgs := make([]string, 0, len(existingImports))
	for pkg := range existingImports {
		existingPkgs = append(existingPkgs, pkg)
	}
	sort.Strings(existingPkgs)
	for _, pkg := range existingPkgs {
		alias := existingImports[pkg]
		oldQual := alias
		if oldQual == "" {
			oldQual = lastGoComponent(pkg)
		}
		if currentAlias, already := f.imports[pkg]; already {
			newQual := currentAlias
			if newQual == "" {
				newQual = lastGoComponent(pkg)
			}
			if oldQual != "" && newQual != "" && oldQual != newQual {
				aliasRenames[oldQual] = newQual
			}
			continue
		}
		chosenAlias := alias
		if oldQual != "" {
			if otherPkg, taken := usedAliases[oldQual]; taken && otherPkg != pkg {
				for idx := 2; ; idx++ {
					candidate := fmt.Sprintf("%s_%d", oldQual, idx)
					if _, candidateTaken := usedAliases[candidate]; !candidateTaken {
						chosenAlias = candidate
						aliasRenames[oldQual] = candidate
						break
					}
				}
			}
			finalQual := chosenAlias
			if finalQual == "" {
				finalQual = oldQual
			}
			usedAliases[finalQual] = pkg
		}
		f.addImport(chosenAlias, pkg)
	}
	if len(aliasRenames) > 0 {
		for i := range filteredExisting {
			if !filteredExisting[i].isCommented {
				filteredExisting[i].rawText = rewritePackageQualifiers(filteredExisting[i].rawText, aliasRenames)
			}
		}
	}

	var merged []generatedBlock
	if f.key.FileName == "types.generated.go" && allBlocksHaveProtoFQN(filteredExisting, currentBlocks) {
		merged = mergeAndSortTypeBlocks(filteredExisting, currentBlocks)
	} else {
		merged = mergeOrderedBlocks(filteredExisting, currentBlocks)
	}

	f.body.Reset()
	for _, b := range merged {
		f.body.WriteString("\n")
		f.body.WriteString(b.rawText)
		f.body.WriteString("\n")
	}
}

func shouldCurrentReplaceExisting(eb, cb generatedBlock) bool {
	if !eb.isCommented && cb.isCommented && eb.protoFQN != "" && cb.protoFQN != "" && eb.protoFQN != cb.protoFQN {
		return false
	}
	return true
}

func discoverValidKRMTypes(baseDir string, currentImports, existingImports map[string]string) map[string]bool {
	const krmPrefix = "github.com/GoogleCloudPlatform/k8s-config-connector/apis/"
	seenDirs := make(map[string]bool)
	var apiDirs []string
	for _, impMap := range []map[string]string{currentImports, existingImports} {
		for pkg := range impMap {
			_, rel, ok := strings.Cut(pkg, krmPrefix)
			if !ok || rel == "" || strings.HasPrefix(rel, "refs/") || strings.HasPrefix(rel, "common/") {
				continue
			}
			apiDir := filepath.Join(baseDir, "apis", filepath.FromSlash(rel))
			if seenDirs[apiDir] {
				continue
			}
			if info, err := os.Stat(apiDir); err == nil && info.IsDir() {
				seenDirs[apiDir] = true
				apiDirs = append(apiDirs, apiDir)
			}
		}
	}
	if len(apiDirs) == 0 {
		return nil
	}
	valid := make(map[string]bool)
	fset := token.NewFileSet()
	for _, apiDir := range apiDirs {
		entries, err := os.ReadDir(apiDir)
		if err != nil {
			continue
		}
		for _, e := range entries {
			if e.IsDir() || !strings.HasSuffix(e.Name(), ".go") || strings.HasSuffix(e.Name(), "_test.go") {
				continue
			}
			src, err := os.ReadFile(filepath.Join(apiDir, e.Name()))
			if err != nil {
				continue
			}
			astFile, err := parser.ParseFile(fset, e.Name(), src, 0)
			if err != nil {
				continue
			}
			for _, decl := range astFile.Decls {
				genDecl, ok := decl.(*ast.GenDecl)
				if !ok || genDecl.Tok != token.TYPE {
					continue
				}
				for _, spec := range genDecl.Specs {
					if ts, ok := spec.(*ast.TypeSpec); ok && ts.Name != nil {
						valid[ts.Name.Name] = true
					}
				}
			}
		}
	}
	return valid
}

func rewritePackageQualifiers(src string, renames map[string]string) string {
	if len(renames) == 0 {
		return src
	}
	fset := token.NewFileSet()
	file := fset.AddFile("", fset.Base(), len(src))
	var s scanner.Scanner
	s.Init(file, []byte(src), nil, scanner.ScanComments)

	type tokSpan struct {
		pos int
		end int
		tok token.Token
		lit string
	}
	var toks []tokSpan
	for {
		pos, tok, lit := s.Scan()
		if tok == token.EOF {
			break
		}
		off := file.Offset(pos)
		length := len(lit)
		if length == 0 {
			length = len(tok.String())
		}
		toks = append(toks, tokSpan{pos: off, end: off + length, tok: tok, lit: lit})
	}

	var out strings.Builder
	last := 0
	for i, t := range toks {
		if t.tok == token.IDENT {
			if newAlias, ok := renames[t.lit]; ok {
				prevIsPeriod := i > 0 && toks[i-1].tok == token.PERIOD
				nextIsPeriod := i+1 < len(toks) && toks[i+1].tok == token.PERIOD
				if !prevIsPeriod && nextIsPeriod {
					out.WriteString(src[last:t.pos])
					out.WriteString(newAlias)
					last = t.end
				}
			}
		}
	}
	out.WriteString(src[last:])
	return out.String()
}

func mergeFileAnnotations(existing, current *annotations.FileAnnotation) *annotations.FileAnnotation {
	if current == nil {
		return existing
	}
	if existing == nil || existing.Key != current.Key {
		return current
	}
	if eg, cg := existing.Attributes["krm.group"], current.Attributes["krm.group"]; len(eg) > 0 && len(cg) > 0 && eg[0] != cg[0] {
		return current
	}

	merged := &annotations.FileAnnotation{
		Key:        current.Key,
		Attributes: make(map[string][]string),
	}
	keys := make(map[string]bool)
	for k := range existing.Attributes {
		keys[k] = true
	}
	for k := range current.Attributes {
		keys[k] = true
	}
	for k := range keys {
		seen := make(map[string]bool)
		var vals []string
		for _, v := range existing.Attributes[k] {
			if !seen[v] {
				seen[v] = true
				vals = append(vals, v)
			}
		}
		for _, v := range current.Attributes[k] {
			if !seen[v] {
				seen[v] = true
				vals = append(vals, v)
			}
		}
		merged.Attributes[k] = vals
	}
	return merged
}

func isTargetOfSeparateGeneratedFile(dir, currentFileName string, currentAnn *annotations.FileAnnotation) bool {
	if currentAnn == nil {
		return false
	}
	currentResources := currentAnn.Attributes["resource"]
	if len(currentResources) == 0 {
		return false
	}
	resSet := make(map[string]bool, len(currentResources))
	for _, r := range currentResources {
		resSet[r] = true
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return false
	}
	for _, e := range entries {
		name := e.Name()
		if name == currentFileName || !strings.HasSuffix(name, "_types.generated.go") {
			continue
		}
		b, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			continue
		}
		anns, err := annotations.FindFileAnnotations(b, []string{"+generated:"})
		if err != nil {
			continue
		}
		for _, a := range anns {
			for _, r := range a.Attributes["resource"] {
				if resSet[r] {
					return true
				}
			}
		}
	}
	return false
}

func hasVersionedMapperFuncs(blocks []generatedBlock) bool {
	for _, b := range blocks {
		if b.kind != "func" {
			continue
		}
		for _, suffix := range []string{"_FromProto", "_ToProto"} {
			if base, ok := strings.CutSuffix(b.name, suffix); ok {
				if idx := strings.LastIndex(base, "_"); idx > 0 {
					ver := base[idx+1:]
					if strings.HasPrefix(ver, "v1") || strings.HasPrefix(ver, "v2") {
						return true
					}
				}
			}
		}
	}
	return false
}

func allBlocksHaveProtoFQN(a, b []generatedBlock) bool {
	for _, blk := range a {
		if blk.protoFQN == "" {
			return false
		}
	}
	for _, blk := range b {
		if blk.protoFQN == "" {
			return false
		}
	}
	return true
}

func mergeAndSortTypeBlocks(existing, current []generatedBlock) []generatedBlock {
	byName := make(map[string]generatedBlock, len(existing)+len(current))
	for _, b := range existing {
		byName[b.name] = b
	}
	for _, b := range current {
		if eb, exists := byName[b.name]; exists && !shouldCurrentReplaceExisting(eb, b) {
			continue
		}
		byName[b.name] = b
	}
	merged := make([]generatedBlock, 0, len(byName))
	for _, b := range byName {
		merged = append(merged, b)
	}
	sort.Slice(merged, func(i, j int) bool {
		if merged[i].isObservedState != merged[j].isObservedState {
			return !merged[i].isObservedState && merged[j].isObservedState
		}
		if merged[i].protoFQN != merged[j].protoFQN {
			return merged[i].protoFQN < merged[j].protoFQN
		}
		return merged[i].name < merged[j].name
	})
	return merged
}

func mergeOrderedBlocks(existing, current []generatedBlock) []generatedBlock {
	currentByName := make(map[string]generatedBlock, len(current))
	var dedupCurrent []generatedBlock
	seenCurrent := make(map[string]int, len(current))
	for _, b := range current {
		currentByName[b.name] = b
		if idx, ok := seenCurrent[b.name]; ok {
			dedupCurrent[idx] = b
		} else {
			seenCurrent[b.name] = len(dedupCurrent)
			dedupCurrent = append(dedupCurrent, b)
		}
	}

	var result []generatedBlock
	placed := make(map[string]bool, len(existing)+len(dedupCurrent))
	for _, eb := range existing {
		if cb, ok := currentByName[eb.name]; ok && shouldCurrentReplaceExisting(eb, cb) {
			result = append(result, cb)
		} else {
			result = append(result, eb)
		}
		placed[eb.name] = true
	}

	for i, cb := range dedupCurrent {
		if placed[cb.name] {
			continue
		}
		inserted := false
		if i > 0 && placed[dedupCurrent[i-1].name] {
			prevName := dedupCurrent[i-1].name
			for idx := range result {
				if result[idx].name == prevName {
					result = append(result[:idx+1], append([]generatedBlock{cb}, result[idx+1:]...)...)
					inserted = true
					break
				}
			}
		}
		if !inserted {
			for j := i + 1; j < len(dedupCurrent); j++ {
				if placed[dedupCurrent[j].name] {
					nextName := dedupCurrent[j].name
					for idx := range result {
						if result[idx].name == nextName {
							result = append(result[:idx], append([]generatedBlock{cb}, result[idx:]...)...)
							inserted = true
							break
						}
					}
					break
				}
			}
		}
		if !inserted {
			result = append(result, cb)
		}
		placed[cb.name] = true
	}
	return result
}

type byteSpan struct {
	start int
	end   int
}

func parseGeneratedGoBlocks(src []byte, defaultPkg string, isBodyOnly bool) ([]generatedBlock, map[string]string, error) {
	goSrc := src
	if isBodyOnly {
		header := fmt.Sprintf("package %s\n\n", defaultPkg)
		goSrc = append([]byte(header), src...)
	}

	fset := token.NewFileSet()
	astFile, err := parser.ParseFile(fset, "", goSrc, parser.ParseComments)
	if err != nil {
		return nil, nil, err
	}

	imports := make(map[string]string)
	for _, imp := range astFile.Imports {
		if imp.Path == nil {
			continue
		}
		pkgPath, err := strconv.Unquote(imp.Path.Value)
		if err != nil {
			continue
		}
		alias := ""
		if imp.Name != nil {
			alias = imp.Name.Name
		}
		imports[pkgPath] = alias
	}

	var blocks []generatedBlock
	var declSpans []byteSpan

	for _, decl := range astFile.Decls {
		switch d := decl.(type) {
		case *ast.GenDecl:
			if d.Tok != token.TYPE || len(d.Specs) == 0 {
				continue
			}
			typeSpec, ok := d.Specs[0].(*ast.TypeSpec)
			if !ok || typeSpec.Name == nil {
				continue
			}
			declStart := fset.Position(d.Pos()).Offset
			docStart := declStart
			if d.Doc != nil && len(d.Doc.List) > 0 {
				firstLineCommentIdx := 0
				for idx, c := range d.Doc.List {
					if strings.HasPrefix(c.Text, "/*") {
						firstLineCommentIdx = idx + 1
					}
				}
				if firstLineCommentIdx < len(d.Doc.List) {
					docStart = fset.Position(d.Doc.List[firstLineCommentIdx].Pos()).Offset
				}
			}
			declEnd := fset.Position(d.End()).Offset
			declSpans = append(declSpans, byteSpan{start: declStart, end: declEnd})

			rawText := strings.TrimSpace(string(goSrc[docStart:declEnd]))
			protoFQN, isObservedState := extractProtoInfoFromBlockText(rawText)
			if strings.HasSuffix(typeSpec.Name.Name, "ObservedState") {
				isObservedState = true
			}
			blocks = append(blocks, generatedBlock{
				name:            typeSpec.Name.Name,
				kind:            "type",
				protoFQN:        protoFQN,
				isObservedState: isObservedState,
				rawText:         rawText,
				offset:          docStart,
			})

		case *ast.FuncDecl:
			if d.Name == nil {
				continue
			}
			declStart := fset.Position(d.Pos()).Offset
			docStart := declStart
			if d.Doc != nil && len(d.Doc.List) > 0 {
				firstLineCommentIdx := 0
				for idx, c := range d.Doc.List {
					if strings.HasPrefix(c.Text, "/*") {
						firstLineCommentIdx = idx + 1
					}
				}
				if firstLineCommentIdx < len(d.Doc.List) {
					docStart = fset.Position(d.Doc.List[firstLineCommentIdx].Pos()).Offset
				}
			}
			declEnd := fset.Position(d.End()).Offset
			declSpans = append(declSpans, byteSpan{start: declStart, end: declEnd})

			rawText := strings.TrimSpace(string(goSrc[docStart:declEnd]))
			krmTypeName := extractKRMTypeFromFuncText(rawText)
			blocks = append(blocks, generatedBlock{
				name:        d.Name.Name,
				kind:        "func",
				krmTypeName: krmTypeName,
				rawText:     rawText,
				offset:      docStart,
			})
		}
	}

	pkgEndOffset := fset.Position(astFile.Name.End()).Offset
	for _, cg := range astFile.Comments {
		for _, c := range cg.List {
			if !strings.HasPrefix(c.Text, "/*") {
				continue
			}
			cOffset := fset.Position(c.Pos()).Offset
			if cOffset <= pkgEndOffset {
				continue
			}
			insideDecl := false
			for _, sp := range declSpans {
				if cOffset >= sp.start && cOffset < sp.end {
					insideDecl = true
					break
				}
			}
			if insideDecl {
				continue
			}
			rawText := strings.TrimSpace(c.Text)
			if name, protoFQN, isObs, ok := parseCommentedTypeBlock(rawText); ok {
				blocks = append(blocks, generatedBlock{
					name:            name,
					kind:            "type",
					isCommented:     true,
					protoFQN:        protoFQN,
					isObservedState: isObs,
					rawText:         rawText,
					offset:          cOffset,
				})
			} else if name, krmTypeName, ok := parseCommentedFuncBlock(rawText); ok {
				blocks = append(blocks, generatedBlock{
					name:        name,
					kind:        "func",
					isCommented: true,
					krmTypeName: krmTypeName,
					rawText:     rawText,
					offset:      cOffset,
				})
			}
		}
	}

	sort.Slice(blocks, func(i, j int) bool {
		return blocks[i].offset < blocks[j].offset
	})
	return blocks, imports, nil
}

func extractProtoInfoFromBlockText(rawText string) (protoFQN string, isObservedState bool) {
	for _, line := range strings.Split(rawText, "\n") {
		trimmed := strings.TrimSpace(line)
		if msg, kind, ok := GetProtoMessageAndKindFromAnnotation(trimmed); ok {
			protoFQN = msg
			if kind == KCCProtoMessageAnnotationObservedState {
				isObservedState = true
			}
			return protoFQN, isObservedState
		}
	}
	return "", false
}

func parseCommentedTypeBlock(rawText string) (typeName, protoFQN string, isObservedState, ok bool) {
	protoFQN, isObservedState = extractProtoInfoFromBlockText(rawText)
	for _, line := range strings.Split(rawText, "\n") {
		trimmed := strings.TrimSpace(line)
		if rest, found := strings.CutPrefix(trimmed, "/* unreachable type "); found {
			fields := strings.Fields(rest)
			if len(fields) > 0 {
				typeName = fields[0]
				break
			}
		}
		if name, found := goTypeNameFromDeclaration(trimmed); found {
			typeName = name
			break
		}
	}
	if typeName == "" {
		return "", "", false, false
	}
	if strings.HasSuffix(typeName, "ObservedState") {
		isObservedState = true
	}
	return typeName, protoFQN, isObservedState, true
}

func parseCommentedFuncBlock(rawText string) (funcName, krmTypeName string, ok bool) {
	for _, line := range strings.Split(rawText, "\n") {
		trimmed := strings.TrimSpace(line)
		if strings.HasPrefix(trimmed, "func ") {
			rest := strings.TrimPrefix(trimmed, "func ")
			if name, _, found := strings.Cut(rest, "("); found && name != "" {
				return strings.TrimSpace(name), extractKRMTypeFromFuncSignature(trimmed), true
			}
		}
	}
	return "", "", false
}

func extractKRMTypeFromFuncText(rawText string) string {
	for _, line := range strings.Split(rawText, "\n") {
		trimmed := strings.TrimSpace(line)
		if strings.HasPrefix(trimmed, "func ") {
			return extractKRMTypeFromFuncSignature(trimmed)
		}
	}
	return ""
}

func extractKRMTypeFromFuncSignature(sigLine string) string {
	rest, ok := strings.CutPrefix(sigLine, "func ")
	if !ok {
		return ""
	}
	rest = strings.TrimSpace(strings.TrimSuffix(strings.TrimSpace(rest), "{"))
	funcName, afterName, ok := strings.Cut(rest, "(")
	if !ok {
		return ""
	}
	params, retType, ok := strings.Cut(afterName, ")")
	if !ok {
		return ""
	}
	retType = strings.TrimSpace(retType)
	if strings.HasSuffix(funcName, "_FromProto") {
		if _, krmType, found := strings.Cut(retType, "."); found {
			return strings.TrimSpace(krmType)
		}
	}
	if strings.HasSuffix(funcName, "_ToProto") {
		if _, secondParam, found := strings.Cut(params, ","); found {
			fields := strings.Fields(secondParam)
			if len(fields) > 0 {
				inType := fields[len(fields)-1]
				if _, krmType, hasDot := strings.Cut(inType, "."); hasDot {
					return strings.TrimSpace(krmType)
				}
			}
		}
		base := strings.TrimSuffix(funcName, "_ToProto")
		if idx := strings.LastIndex(base, "_"); idx > 0 {
			return base[:idx]
		}
	}
	return ""
}

func scanHandwrittenDirDeclarations(srcDir, currentFileName string) (typeNames map[string]bool, protoTagged map[string]bool, funcNames map[string]bool) {
	typeNames = make(map[string]bool)
	protoTagged = make(map[string]bool)
	funcNames = make(map[string]bool)

	files, err := os.ReadDir(srcDir)
	if err != nil {
		return typeNames, protoTagged, funcNames
	}
	for _, f := range files {
		name := f.Name()
		if !strings.HasSuffix(name, ".go") || name == currentFileName || name == "zz_generated.deepcopy.go" || strings.HasSuffix(name, "_test.go") {
			continue
		}
		p := filepath.Join(srcDir, name)
		b, err := os.ReadFile(p)
		if err != nil {
			continue
		}
		if strings.HasSuffix(name, "generated.go") {
			blocks, _, err := parseGeneratedGoBlocks(b, "p", false)
			if err != nil {
				continue
			}
			for _, blk := range blocks {
				if blk.isCommented || blk.name == "" {
					continue
				}
				if blk.kind == "type" {
					typeNames[blk.name] = true
					if blk.protoFQN != "" {
						protoTagged[blk.protoFQN] = true
					}
				} else if blk.kind == "func" {
					funcNames[blk.name] = true
				}
			}
			continue
		}
		protoLines := make(map[string]string)
		content := string(b)
		scanFileDeclarations(content, typeNames, protoLines)
		for protoMsg := range protoLines {
			protoTagged[protoMsg] = true
		}
		for _, line := range strings.Split(content, "\n") {
			trimmed := strings.TrimSpace(line)
			if rest, ok := strings.CutPrefix(trimmed, "func "); ok {
				if fnName, _, found := strings.Cut(rest, "("); found && fnName != "" && !strings.Contains(fnName, " ") {
					funcNames[fnName] = true
				}
			}
		}
	}
	return typeNames, protoTagged, funcNames
}


// usedImports returns the imports referenced by the generated file body, ensuring
// any qualifiers from QualifierImports present in the body are included.
//
// An import is treated as used if the body contains "<qualifier>.". The qualifier
// is the explicit alias if defined, or the last path segment of the package import path.
func (f *generatedFile) usedImports() map[string]string {
	body := f.body.String()

	// Ensure all standard external types defined in protoMessagesNotMappedToGoStruct
	// (such as apiextensionsv1.JSON) have their packages imported if their qualifier appears in the body.
	for qualifier, pkgName := range QualifierImports {
		if _, already := f.imports[pkgName]; already {
			continue
		}
		if strings.Contains(body, qualifier+".") {
			f.addImport(qualifier, pkgName)
		}
	}

	if len(f.imports) == 0 {
		return nil
	}
	used := make(map[string]string, len(f.imports))
	for pkgName, alias := range f.imports {
		qualifier := alias
		if qualifier == "" {
			qualifier = lastGoComponent(pkgName)
		}
		if strings.Contains(body, qualifier+".") {
			used[pkgName] = alias
		}
	}
	return used
}

// extractCopyrightYear extracts the copyright year from the given file bytes
func extractCopyrightYear(b []byte) (int, bool) {
	s := string(b)
	for _, line := range strings.Split(s, "\n") {
		if suffix, ok := strings.CutPrefix(line, "// Copyright "); ok {
			tokens := strings.Fields(suffix)
			if len(tokens) >= 1 {
				year, err := strconv.Atoi(tokens[0])
				if err == nil {
					return year, true
				}
			}
		}
	}

	return 0, false
}

func (g *generatorBase) WriteFiles(addCopyright bool, writeEmptyFiles bool) error {
	for _, f := range g.generatedFiles {
		if err := f.Write(addCopyright, writeEmptyFiles, g.onlyUsedImports); err != nil {
			return err
		}
	}
	return nil
}

func (g *generatorBase) findTypeDeclaration(goTypeName string, srcDir string, skipGenerated bool) (*string, error) {
	files, err := os.ReadDir(srcDir)
	if err != nil {
		if os.IsNotExist(err) { // type declaration does not exist
			return nil, nil
		}
		return nil, fmt.Errorf("reading directory %q: %w", srcDir, err)
	}

	for _, f := range files {
		p := filepath.Join(srcDir, f.Name())
		if !strings.HasSuffix(p, ".go") {
			continue
		}
		if skipGenerated && strings.HasSuffix(p, "generated.go") {
			continue
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return nil, fmt.Errorf("reading file %q: %w", p, err)
		}

		for _, line := range strings.Split(string(b), "\n") {
			line = strings.TrimSpace(line)
			if strings.HasPrefix(line, "type "+goTypeName+" ") {
				return &line, nil
			}
		}
	}

	return nil, nil
}

func (g *generatorBase) findTypeDeclarationWithProtoTag(protoTag string, srcDir string, skipGenerated bool) (*string, error) {
	files, err := os.ReadDir(srcDir)
	if err != nil {
		return nil, fmt.Errorf("reading directory %q: %w", srcDir, err)
	}

	for _, f := range files {
		p := filepath.Join(srcDir, f.Name())
		if !strings.HasSuffix(p, ".go") {
			continue
		}
		if skipGenerated && strings.HasSuffix(p, "generated.go") {
			continue
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return nil, fmt.Errorf("reading file %q: %w", p, err)
		}

		for _, line := range strings.Split(string(b), "\n") {
			if proto, ok := GetProtoMessageFromAnnotation(line); ok {
				if proto == protoTag {
					return &line, nil
				}
			}
		}
	}

	return nil, nil
}

