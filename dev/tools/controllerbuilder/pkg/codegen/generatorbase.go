type generatorBase struct {
	outputBaseDir  string
	generatedFiles map[generatedFileKey]*generatedFile
	errors         []error

	// nonAutogeneratedCache memoizes scanNonAutogeneratedTypes per source directory.
	nonAutogeneratedCache map[string]*nonAutogeneratedTypes

	// onlyUsedImports filters imports written to generated files so that only packages
	// referenced in the rendered file body are emitted, while also ensuring required
	// qualifier imports are included.
	onlyUsedImports bool
}

func (g *generatorBase) init(outputBaseDir string) {
	g.outputBaseDir = outputBaseDir
	g.generatedFiles = make(map[generatedFileKey]*generatedFile)
	g.nonAutogeneratedCache = make(map[string]*nonAutogeneratedTypes)
}

// nonAutogeneratedTypes tracks type names and proto annotations declared in non-autogenerated
// files within the target package, preventing conflicting declarations or orphaned ObservedState structs.
type nonAutogeneratedTypes struct {
	// typeNames contains all Go type names declared in non-autogenerated files.
	typeNames map[string]bool
	// protoTagged contains all protobuf message full names associated with +kcc:*proto annotations
	// in non-autogenerated files.
	protoTagged map[string]bool
}

// ownedByGenerator reports whether a proto message is safely manageable by the generator,
// verifying that neither its proto name nor its generated Go type names (base or ObservedState)
// collide with existing non-autogenerated declarations in the package.
func (h *nonAutogeneratedTypes) ownedByGenerator(protoFullName string, goName string, observedStateGoName string) bool {
	if h == nil {
		return true
	}
	return !h.protoTagged[protoFullName] && !h.typeNames[goName] && !h.typeNames[observedStateGoName]
}

// scanNonAutogeneratedTypes scans non-autogenerated Go files in srcDir and records their type declarations
// and proto annotations, caching the result per directory. A missing directory is not an error:
// a service generated for the first time does not have one yet.
func (g *generatorBase) scanNonAutogeneratedTypes(srcDir string) (*nonAutogeneratedTypes, error) {
	if cached, ok := g.nonAutogeneratedCache[srcDir]; ok {
		return cached, nil
	}

	out := &nonAutogeneratedTypes{
		typeNames:   make(map[string]bool),
		protoTagged: make(map[string]bool),
	}

	files, err := os.ReadDir(srcDir)
	if err != nil {
		if os.IsNotExist(err) {
			g.nonAutogeneratedCache[srcDir] = out
			return out, nil
		}
		return nil, fmt.Errorf("reading directory %q: %w", srcDir, err)
	}

	for _, f := range files {
		p := filepath.Join(srcDir, f.Name())
		if !strings.HasSuffix(p, ".go") || strings.HasSuffix(p, "generated.go") {
			continue
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return nil, fmt.Errorf("reading file %q: %w", p, err)
		}
		for _, line := range strings.Split(string(b), "\n") {
			line = strings.TrimSpace(line)
			if protoMessage, _, ok := GetProtoMessageAndKindFromAnnotation(line); ok {
				out.protoTagged[protoMessage] = true
				continue
			}
			if name, ok := goTypeNameFromDeclaration(line); ok {
				out.typeNames[name] = true
			}
		}
	}

	g.nonAutogeneratedCache[srcDir] = out
	return out, nil
}

// goTypeNameFromDeclaration extracts the type name from a "type <Name> ..." declaration line.
func goTypeNameFromDeclaration(line string) (string, bool) {
	rest, ok := strings.CutPrefix(line, "type ")
	if !ok {
		return "", false
	}
	name, _, ok := strings.Cut(rest, " ")
	if !ok || name == "" {
		return "", false
	}
	return name, true
}

func (g *generatorBase) getOutputFile(k generatedFileKey) *generatedFile {
	out := g.generatedFiles[k]
	if out == nil {
		out = &generatedFile{key: k, baseDir: g.outputBaseDir}
		g.generatedFiles[k] = out
	}
	return out
}

func (g *generatorBase) Errorf(msg string, args ...any) {
	g.errors = append(g.errors, fmt.Errorf(msg, args...))
}

type generatedFile struct {
	baseDir   string
	key       generatedFileKey
	goPackage string
	body      bytes.Buffer

	fileAnnotation *annotations.FileAnnotation

	imports map[string]string
}

type generatedFileKey struct {
	GoPackage string

	FileName string
}

func (f *generatedFile) OutputDir() string {
	tokens := strings.Split(f.key.GoPackage, ".")
	dirTokens := []string{f.baseDir}
	dirTokens = append(dirTokens, tokens...)
	dir := filepath.Join(dirTokens...)
	return dir
}

func (f *generatedFile) addImport(alias string, pkgName string) {
	if f.imports == nil {
		f.imports = make(map[string]string)
	}
	f.imports[pkgName] = alias
}

func (f *generatedFile) Write(addCopyright bool, writeEmptyFiles bool, onlyUsedImports bool) error {
	if f.body.Len() == 0 && !writeEmptyFiles {
		return nil
	}

	dir := f.OutputDir()
	p := filepath.Join(dir, f.key.FileName)

	if err := os.MkdirAll(dir, 0755); err != nil {
		return fmt.Errorf("creating directory %q: %w", dir, err)
	}

	var w bytes.Buffer

	if addCopyright {
		year := time.Now().Year()

		b, err := os.ReadFile(p)
		if err != nil && !os.IsNotExist(err) {
			return fmt.Errorf("reading file %q (checking for existing copyright): %w", p, err)
		} else {
			existingCopyrightYear, ok := extractCopyrightYear(b)
			if ok {
				year = existingCopyrightYear
			}
		}
		writeCopyright(&w, year)
	}

	fmt.Fprintf(&w, "// Code generated by dev/tasks/generate-all. DO NOT EDIT.\n")

	if f.key.FileName == "mapper.generated.go" {
		fmt.Fprintf(&w, "//go:build !ignore_autogenerated\n")
		fmt.Fprintf(&w, "// +build !ignore_autogenerated\n\n")
	}

	if f.fileAnnotation != nil {
		s := f.fileAnnotation.FormatGo()
		fmt.Fprintf(&w, "%s\n", s)
	}

	if f.goPackage != "" {
		fmt.Fprintf(&w, "package %s\n", f.goPackage)
		fmt.Fprintf(&w, "\n")
	}

	// Filter imports to only those referenced in the generated body when onlyUsedImports
	// is set, preventing unused import compilation errors for skipped types.
	used := f.imports
	if onlyUsedImports {
		used = f.usedImports()
	}
	if len(used) != 0 {
		w.WriteString("import (\n")
		for pkgName, alias := range used {
			if alias == "" {
				w.WriteString(fmt.Sprintf("\t%q\n", pkgName))
			} else {
				w.WriteString(fmt.Sprintf("\t%s %q\n", alias, pkgName))
			}
		}
		w.WriteString(")\n")
	}
	f.body.WriteTo(&w)

	formatted, err := imports.Process(p, w.Bytes(), nil)
	if err != nil {
		klog.Errorf("error from goimports processing file %q:\n%s", p, w.String())
		return fmt.Errorf("running goimports on %q: %w", p, err)
	}

	klog.V(2).Infof("writing file %v", p)
	if err := os.WriteFile(p, formatted, 0644); err != nil {
		return fmt.Errorf("writing %q: %w", p, err)
	}

	return nil
}

// usedImports returns the imports referenced by the generated file body, ensuring
// any qualifiers from QualifierImports present in the body are included.
//
// An import is treated as used if the body contains "<qualifier>.". The qualifier
// is the explicit alias if defined, or the last path segment of the package import path.
func (f *generatedFile) usedImports() map[string]string {
	body := f.body.String()

	// Ensure all standard external types defined in protoMessagesNotMappedToGoStruct
	// (such as apiextensionsv1.JSON) have their packages imported if their qualifier appears in the body.
	for qualifier, pkgName := range QualifierImports {
		if _, already := f.imports[pkgName]; already {
			continue
		}
		if strings.Contains(body, qualifier+".") {
			f.addImport(qualifier, pkgName)
		}
	}

	if len(f.imports) == 0 {
		return nil
	}
	used := make(map[string]string, len(f.imports))
	for pkgName, alias := range f.imports {
		qualifier := alias
		if qualifier == "" {
			qualifier = lastGoComponent(pkgName)
		}
		if strings.Contains(body, qualifier+".") {
			used[pkgName] = alias
		}
	}
	return used
}

// extractCopyrightYear extracts the copyright year from the given file bytes
func extractCopyrightYear(b []byte) (int, bool) {
	s := string(b)
	for _, line := range strings.Split(s, "\n") {
		if suffix, ok := strings.CutPrefix(line, "// Copyright "); ok {
			tokens := strings.Fields(suffix)
			if len(tokens) >= 1 {
				year, err := strconv.Atoi(tokens[0])
				if err == nil {
					return year, true
				}
			}
		}
	}

	return 0, false
}

func (g *generatorBase) WriteFiles(addCopyright bool, writeEmptyFiles bool) error {
	for _, f := range g.generatedFiles {
		if err := f.Write(addCopyright, writeEmptyFiles, g.onlyUsedImports); err != nil {
			return err
		}
	}
	return nil
}

func (g *generatorBase) findTypeDeclaration(goTypeName string, srcDir string, skipGenerated bool) (*string, error) {
	files, err := os.ReadDir(srcDir)
	if err != nil {
		if os.IsNotExist(err) { // type declaration does not exist
			return nil, nil
		}
		return nil, fmt.Errorf("reading directory %q: %w", srcDir, err)
	}

	for _, f := range files {
		p := filepath.Join(srcDir, f.Name())
		if !strings.HasSuffix(p, ".go") {
			continue
		}
		if skipGenerated && strings.HasSuffix(p, "generated.go") {
			continue
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return nil, fmt.Errorf("reading file %q: %w", p, err)
		}

		for _, line := range strings.Split(string(b), "\n") {
			line = strings.TrimSpace(line)
			if strings.HasPrefix(line, "type "+goTypeName+" ") {
				return &line, nil
			}
		}
	}

	return nil, nil
}

func (g *generatorBase) findTypeDeclarationWithProtoTag(protoTag string, srcDir string, skipGenerated bool) (*string, error) {
	files, err := os.ReadDir(srcDir)
	if err != nil {
		return nil, fmt.Errorf("reading directory %q: %w", srcDir, err)
	}

	for _, f := range files {
		p := filepath.Join(srcDir, f.Name())
		if !strings.HasSuffix(p, ".go") {
			continue
		}
		if skipGenerated && strings.HasSuffix(p, "generated.go") {
			continue
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return nil, fmt.Errorf("reading file %q: %w", p, err)
		}

		for _, line := range strings.Split(string(b), "\n") {
			if proto, ok := GetProtoMessageFromAnnotation(line); ok {
				if proto == protoTag {
					return &line, nil
				}
			}
		}
	}

	return nil, nil
}

func (g *generatorBase) findFuncDeclaration(goFuncName string, srcDir string, skipGenerated bool) *string {
	files, err := os.ReadDir(srcDir)
	if err != nil {
		g.Errorf("reading directory %q: %w", srcDir, err)
		return nil
	}

	for _, f := range files {
		p := filepath.Join(srcDir, f.Name())
		if !strings.HasSuffix(p, ".go") {
			continue
		}
		if skipGenerated && strings.HasSuffix(p, "generated.go") {
			continue
		}
		b, err := os.ReadFile(p)
		if err != nil {
			g.Errorf("reading file %q: %w", p, err)
			return nil
		}

		for _, line := range strings.Split(string(b), "\n") {
			line = strings.TrimSpace(line)
			if strings.HasPrefix(line, "func "+goFuncName+"(") {
				return &line
			}
		}
	}

	return nil
}
