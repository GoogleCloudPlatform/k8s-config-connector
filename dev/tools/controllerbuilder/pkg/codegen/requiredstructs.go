// RequiredFromProtoMarker on a <Kind>Spec opts the Kind in to +required on
// the fields the proto marks REQUIRED.
//
// With --emit-required-from-proto, the scaffold adds it to each new
// <kind>_types.go. Existing Kinds lack it and keep their optional fields,
// since making a field required breaks objects that omit it. To opt in an
// existing Kind, add the marker by hand.
const RequiredFromProtoMarker = "+kcc:required-from-proto"

// IsRequiredFromProtoMarker reports whether a comment line is the marker.
func IsRequiredFromProtoMarker(line string) bool {
	return strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(line), "//")) == RequiredFromProtoMarker
}

// RequiredStructName is the name of msg's Required copy: the plain name plus
// "Required". Opted-in Kinds use the copy when msg has other users.
func RequiredStructName(msg protoreflect.MessageDescriptor) string {
	return GoNameForProtoMessage(msg) + "Required"
}

// specStructName is the struct that a spec field of type msg holds: the
// Required copy if msg is split and the field is in a strict struct, else the
// plain struct.
func specStructName(msg protoreflect.MessageDescriptor, opts WriteOptions) string {
	if opts.RequiredStructs[string(msg.FullName())] {
		return RequiredStructName(msg)
	}
	return GoNameForProtoMessage(msg)
}

// RequiredUses records the hand-written code that uses a package's types.
type RequiredUses struct {
	// MarkedKinds are the Kinds whose Spec has RequiredFromProtoMarker.
	MarkedKinds map[string]bool
	// MarkedSpecs are the opted-in Specs, by type name.
	MarkedSpecs map[string]bool
	// HandWritten maps each type the package declares by hand to the type
	// names its declaration uses.
	HandWritten map[string]map[string]bool
	// FromOtherPackages are the types that other packages under apis/ use.
	FromOtherPackages map[string]bool
}

// ScanRequiredUses reads the hand-written Go files in pkgDir, and the Go files
// of every other package under apisDir that imports importPath. It records
// what each hand-written type uses, so PlanRequiredStructs can follow
// hand-written types.
func ScanRequiredUses(pkgDir, apisDir, importPath string) (*RequiredUses, error) {
	uses := &RequiredUses{
		MarkedKinds:       map[string]bool{},
		MarkedSpecs:       map[string]bool{},
		HandWritten:       map[string]map[string]bool{},
		FromOtherPackages: map[string]bool{},
	}
	if err := uses.scanPackage(pkgDir); err != nil {
		return nil, err
	}
	if apisDir == "" {
		return uses, nil
	}
	if err := uses.scanImporters(apisDir, pkgDir, importPath); err != nil {
		return nil, err
	}
	return uses, nil
}

// scanPackage records the types that the package's hand-written files
// declare.
func (u *RequiredUses) scanPackage(dir string) error {
	entries, err := os.ReadDir(dir)
	if os.IsNotExist(err) {
		// A service generated for the first time has no package yet.
		return nil
	}
	if err != nil {
		return fmt.Errorf("reading %s: %w", dir, err)
	}
	fset := token.NewFileSet()
	for _, e := range entries {
		if !isHandWrittenSource(e) {
			continue
		}
		if err := u.scanFile(fset, filepath.Join(dir, e.Name())); err != nil {
			return err
		}
	}
	return nil
}

// isHandWrittenSource reports whether e is a hand-written Go file. It skips
// tests and generated files: types.generated.go is about to be rewritten, and
// deepcopy declares no types. scanNonAutogeneratedTypes also skips
// generated.go files.
func isHandWrittenSource(e fs.DirEntry) bool {
	name := e.Name()
	return !e.IsDir() && isGoSource(name) && !strings.HasSuffix(name, "generated.go") && !strings.HasPrefix(name, "zz_generated")
}

// scanFile records the types that a hand-written file declares.
func (u *RequiredUses) scanFile(fset *token.FileSet, p string) error {
	f, err := parser.ParseFile(fset, p, nil, parser.ParseComments)
	if err != nil {
		return fmt.Errorf("parsing %s: %w", p, err)
	}
	for _, t := range declaredTypes(f) {
		u.recordType(t)
	}
	return nil
}

// declaredType is a type that a hand-written file declares.
type declaredType struct {
	spec *ast.TypeSpec
	// doc is the type's doc comment.
	doc *ast.CommentGroup
}

// declaredTypes returns the types that a file declares.
func declaredTypes(f *ast.File) []declaredType {
	var out []declaredType
	for _, decl := range f.Decls {
		if gd, ok := decl.(*ast.GenDecl); ok && gd.Tok == token.TYPE {
			out = append(out, typesIn(gd)...)
		}
	}
	return out
}

// typesIn returns the types that a type declaration declares.
func typesIn(gd *ast.GenDecl) []declaredType {
	var out []declaredType
	for _, spec := range gd.Specs {
		ts, ok := spec.(*ast.TypeSpec)
		if !ok {
			continue
		}
		doc := ts.Doc
		if doc == nil && len(gd.Specs) == 1 {
			// A declaration of one type holds that type's doc comment.
			doc = gd.Doc
		}
		out = append(out, declaredType{spec: ts, doc: doc})
	}
	return out
}

// recordType records what a hand-written type uses, and whether it is an
// opted-in Spec.
func (u *RequiredUses) recordType(t declaredType) {
	name := t.spec.Name.Name
	if kind, ok := t.markedKind(); ok {
		u.MarkedKinds[kind] = true
		u.MarkedSpecs[name] = true
	}
	u.HandWritten[name] = t.typeRefs()
}

// markedKind returns the Kind whose Spec t is, if t has
// RequiredFromProtoMarker.
func (t declaredType) markedKind() (string, bool) {
	kind, ok := strings.CutSuffix(t.spec.Name.Name, "Spec")
	if !ok || kind == "" || !hasRequiredFromProtoMarker(t.doc) {
		return "", false
	}
	return kind, true
}

func hasRequiredFromProtoMarker(doc *ast.CommentGroup) bool {
	if doc == nil {
		return false
	}
	for _, c := range doc.List {
		if IsRequiredFromProtoMarker(c.Text) {
			return true
		}
	}
	return false
}

// typeRefs returns the type names that t's declaration uses.
func (t declaredType) typeRefs() map[string]bool {
	refs := map[string]bool{}
	collectTypeRefs(t.spec.Type, refs)
	return refs
}

// collectTypeRefs adds each type name in a type expression to refs, skipping
// types from other packages.
func collectTypeRefs(expr ast.Expr, refs map[string]bool) {
	switch t := expr.(type) {
	case *ast.Ident:
		refs[t.Name] = true
	case *ast.StarExpr:
		collectTypeRefs(t.X, refs)
	case *ast.ArrayType:
		collectTypeRefs(t.Elt, refs)
	case *ast.MapType:
		collectTypeRefs(t.Key, refs)
		collectTypeRefs(t.Value, refs)
	case *ast.ParenExpr:
		collectTypeRefs(t.X, refs)
	case *ast.StructType:
		for _, f := range t.Fields.List {
			collectTypeRefs(f.Type, refs)
		}
	}
}

// scanImporters records which of the package's types other packages under
// apisDir use, such as a v1alpha1 Spec that holds a v1beta1 struct. The
// generator can't see those uses any other way.
func (u *RequiredUses) scanImporters(apisDir, pkgDir, importPath string) error {
	skip := filepath.Clean(pkgDir)
	fset := token.NewFileSet()
	err := filepath.WalkDir(apisDir, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() && filepath.Clean(p) == skip {
			return filepath.SkipDir
		}
		if d.IsDir() || !isGoSource(d.Name()) || strings.HasPrefix(d.Name(), "zz_generated") {
			return nil
		}
		return u.scanImporterFile(fset, p, importPath)
	})
	if os.IsNotExist(err) {
		return nil
	}
	return err
}

// scanImporterFile records the package's types that a file uses, if the file
// imports the package.
func (u *RequiredUses) scanImporterFile(fset *token.FileSet, p, importPath string) error {
	b, err := os.ReadFile(p)
	if err != nil {
		return err
	}
	// Parse only the files that mention the import path.
	if !bytes.Contains(b, []byte(strconv.Quote(importPath))) {
		return nil
	}
	f, err := parser.ParseFile(fset, p, b, 0)
	if err != nil {
		return fmt.Errorf("parsing %s: %w", p, err)
	}
	alias := importName(f, importPath)
	if alias == "" {
		return nil
	}
	ast.Inspect(f, func(n ast.Node) bool {
		if sel, ok := n.(*ast.SelectorExpr); ok && isIdent(sel.X, alias) {
			u.FromOtherPackages[sel.Sel.Name] = true
		}
		return true
	})
	return nil
}

// importName returns the name a file uses for importPath, or "" if the file
// doesn't import it by name.
func importName(f *ast.File, importPath string) string {
	for _, imp := range f.Imports {
		p, err := strconv.Unquote(imp.Path.Value)
		if err != nil || p != importPath {
			continue
		}
		if imp.Name == nil {
			return path.Base(importPath)
		}
		if imp.Name.Name == "_" || imp.Name.Name == "." {
			return ""
		}
		return imp.Name.Name
	}
	return ""
}

// isIdent reports whether expr is the identifier name.
func isIdent(expr ast.Expr, name string) bool {
	id, ok := expr.(*ast.Ident)
	return ok && id.Name == name
}

func isGoSource(name string) bool {
	return strings.HasSuffix(name, ".go") && !strings.HasSuffix(name, "_test.go")
}

// requiredPlan says which structs WriteVisitedMessages writes for each
// message. Keys are full proto names.
type requiredPlan struct {
	// strict holds the messages that opted-in Specs use, directly or through
	// other structs. Their struct gets +required markers.
	strict map[string]bool
	// lenient holds the messages that anything else uses. Their struct keeps
	// every field optional.
	lenient map[string]bool
	// split holds the messages in both sets whose two versions differ. Each
	// gets a lenient plain struct and a strict <Name>Required copy.
	split map[string]bool
}

// PlanRequiredStructs decides which structs get +required markers. Call it
// after VisitProto and before WriteVisitedMessages.
//
// A message that an opted-in Spec uses, directly or through other structs,
// gets a strict struct. A message that anything else uses gets a lenient one:
// a Kind, a status, an unmarked Spec or another package. Both walks follow
// hand-written types, so a struct that only opted-in Kinds use is strict even
// through a hand-written helper. A message that needs both keeps its plain name lenient, so its
// current users don't change, and gets a strict <Name>Required copy. A copy
// that code already uses is always written.
//
// newSpecFields are the top-level Spec fields of the Kinds this run
// scaffolds. Those Kinds get the marker, so their fields are strict uses.
func (g *TypeGenerator) PlanRequiredStructs(uses *RequiredUses, newSpecFields []protoreflect.FieldDescriptor) {
	if uses == nil {
		uses = &RequiredUses{}
	}
	p := g.newRequiredPlanner(uses)
	named := p.requiredCopiesInUse()
	strictReached := p.walk(p.strictSeeds(named, newSpecFields), neverStop)
	// The lenient walk stops at opted-in Specs, so a Kind that holds its own
	// Spec doesn't make it lenient.
	lenientReached := p.walk(p.lenientSeeds(strictReached), p.isMarkedSpec)
	strict := messagesIn(strictReached)
	lenient := messagesIn(lenientReached)
	split := p.splitMessages(strict, lenient, named)
	g.requiredPlan = &requiredPlan{strict: strict, lenient: lenient, split: split}
}

// structNode is a struct the walks visit: the struct of a message the
// generator writes, or a type declared by hand. Exactly one field is set.
type structNode struct {
	// message is the full name of a message the generator writes.
	message string
	// handWritten is the name of a type declared by hand.
	handWritten string
}

// requiredPlanner holds what PlanRequiredStructs needs to walk from struct to
// struct, through generated and hand-written code.
type requiredPlanner struct {
	g    *TypeGenerator
	uses *RequiredUses
	// written holds the messages the generator writes, by full name.
	written map[string]protoreflect.MessageDescriptor
	// byName and byRequiredName map the plain and Required struct names of
	// the written messages to their full names.
	byName         map[string]string
	byRequiredName map[string]string
}

func (g *TypeGenerator) newRequiredPlanner(uses *RequiredUses) *requiredPlanner {
	p := &requiredPlanner{
		g:              g,
		uses:           uses,
		written:        g.messagesToWrite(),
		byName:         map[string]string{},
		byRequiredName: map[string]string{},
	}
	for fqn, msg := range p.written {
		p.byName[GoNameForProtoMessage(msg)] = fqn
		p.byRequiredName[RequiredStructName(msg)] = fqn
	}
	return p
}

// requiredCopiesInUse returns the messages whose Required copy code already
// uses. Code that uses a Required copy needs it, wherever that code is.
func (p *requiredPlanner) requiredCopiesInUse() map[string]bool {
	named := map[string]bool{}
	for _, name := range p.usedNames() {
		if fqn, ok := p.requiredCopyOf(name); ok {
			named[fqn] = true
		}
	}
	return named
}

// usedNames returns the type names that hand-written code uses, in this
// package or in another.
func (p *requiredPlanner) usedNames() []string {
	used := map[string]bool{}
	for _, names := range p.uses.HandWritten {
		for name := range names {
			used[name] = true
		}
	}
	for name := range p.uses.FromOtherPackages {
		used[name] = true
	}
	return sortedKeys(used)
}

// requiredCopyOf returns the message whose Required copy has the given name.
func (p *requiredPlanner) requiredCopyOf(name string) (string, bool) {
	// Check type names first: a message or a hand-written type can be called
	// FooRequired without being Foo's copy.
	if _, ok := p.byName[name]; ok || p.g.declaredByHand(name) {
		return "", false
	}
	fqn, ok := p.byRequiredName[name]
	return fqn, ok
}

// strictSeeds returns where the strict walk starts: the Required copies in
// use, the opted-in Specs, and the Spec fields of the Kinds this run
// scaffolds.
func (p *requiredPlanner) strictSeeds(named map[string]bool, newSpecFields []protoreflect.FieldDescriptor) []structNode {
	var seeds []structNode
	for _, fqn := range sortedKeys(named) {
		seeds = append(seeds, structNode{message: fqn})
	}
	for _, name := range sortedKeys(p.uses.MarkedSpecs) {
		seeds = append(seeds, structNode{handWritten: name})
	}
	for _, f := range newSpecFields {
		if n, ok := p.nodeForSpecField(f); ok {
			seeds = append(seeds, n)
		}
	}
	return seeds
}

// lenientSeeds returns where the lenient walk starts. Every hand-written type
// that the strict walk doesn't reach starts it: a Kind, a status, an unmarked
// Spec, or a type nothing uses. A type that only opted-in Specs use doesn't,
// so what it holds stays strict. The types other packages use, and the plain
// structs in statuses, start it too.
func (p *requiredPlanner) lenientSeeds(strictReached map[structNode]bool) []structNode {
	var seeds []structNode
	for _, name := range sortedKeys(p.uses.HandWritten) {
		n := structNode{handWritten: name}
		if !strictReached[n] {
			seeds = append(seeds, n)
		}
	}
	for _, name := range sortedKeys(p.uses.FromOtherPackages) {
		if n, ok := p.nodeForType(name); ok {
			seeds = append(seeds, n)
		}
	}
	return append(seeds, p.statusSeeds()...)
}

// statusSeeds returns the plain structs that ObservedState structs hold. An
// ObservedState struct holds a message's plain struct when the message has no
// ObservedState struct of its own, and for map values. Those must stay
// lenient, or +required ends up in the status schema.
func (p *requiredPlanner) statusSeeds() []structNode {
	var seeds []structNode
	for _, details := range p.g.outputMessages {
		for _, f := range details.OutputFields {
			if n, ok := p.nodeForStatusField(f); ok {
				seeds = append(seeds, n)
			}
		}
	}
	return seeds
}

// isMarkedSpec reports whether n is an opted-in Spec.
func (p *requiredPlanner) isMarkedSpec(n structNode) bool {
	return p.uses.MarkedSpecs[n.handWritten]
}

// walk returns the nodes that seeds reach. It doesn't enter a node for which
// stop returns true.
func (p *requiredPlanner) walk(seeds []structNode, stop func(structNode) bool) map[structNode]bool {
	reached := map[structNode]bool{}
	queue := append([]structNode(nil), seeds...)
	for len(queue) > 0 {
		n := queue[0]
		queue = queue[1:]
		if reached[n] || stop(n) {
			continue
		}
		reached[n] = true
		queue = append(queue, p.next(n)...)
	}
	return reached
}

// neverStop lets a walk enter every node.
func neverStop(structNode) bool { return false }

// next returns the nodes for the structs that n holds.
func (p *requiredPlanner) next(n structNode) []structNode {
	if n.message != "" {
		return p.heldBy(p.written[n.message])
	}
	return p.usedBy(n.handWritten)
}

// heldBy returns the nodes for the structs that msg's struct holds.
func (p *requiredPlanner) heldBy(msg protoreflect.MessageDescriptor) []structNode {
	var out []structNode
	for _, f := range structFields(msg) {
		if n, ok := p.nodeForSpecField(f); ok {
			out = append(out, n)
		}
	}
	return out
}

// usedBy returns the nodes for the types that a hand-written type's
// declaration uses.
func (p *requiredPlanner) usedBy(name string) []structNode {
	var out []structNode
	for _, used := range sortedKeys(p.uses.HandWritten[name]) {
		if n, ok := p.nodeForType(used); ok {
			out = append(out, n)
		}
	}
	return out
}

// nodeForSpecField returns the node for the struct that a spec field holds.
func (p *requiredPlanner) nodeForSpecField(f protoreflect.FieldDescriptor) (structNode, bool) {
	child, ok := specChild(f, p.g.writeOptions)
	if !ok {
		return structNode{}, false
	}
	return p.nodeForMessage(child)
}

// nodeForStatusField returns the node for the plain struct that an
// ObservedState field holds.
func (p *requiredPlanner) nodeForStatusField(f protoreflect.FieldDescriptor) (structNode, bool) {
	child, ok := plainChildInStatus(f, p.g.observedStateMessages, p.g.writeOptions)
	if !ok {
		return structNode{}, false
	}
	return p.nodeForMessage(child)
}

// nodeForMessage returns the node for msg's struct. If the generator doesn't
// write msg, the node is the hand-written type that stands in for it.
func (p *requiredPlanner) nodeForMessage(msg protoreflect.MessageDescriptor) (structNode, bool) {
	fqn := string(msg.FullName())
	if p.written[fqn] != nil {
		return structNode{message: fqn}, true
	}
	return p.nodeForType(GoNameForProtoMessage(msg))
}

// nodeForType returns the node that a type name refers to. It returns false
// for a name that is neither a written message nor a hand-written type, such
// as string.
func (p *requiredPlanner) nodeForType(name string) (structNode, bool) {
	if fqn, ok := p.byName[name]; ok {
		return structNode{message: fqn}, true
	}
	if _, ok := p.uses.HandWritten[name]; ok {
		return structNode{handWritten: name}, true
	}
	return structNode{}, false
}

// messagesIn returns the full names of the messages among nodes.
func messagesIn(nodes map[structNode]bool) map[string]bool {
	out := map[string]bool{}
	for n := range nodes {
		if n.message != "" {
			out[n.message] = true
		}
	}
	return out
}

// splitMessages returns the strict messages that get both a lenient plain
// struct and a strict Required copy. Splitting a message can make its parents
// need a split too, including through cycles, so it loops until nothing
// changes.
func (p *requiredPlanner) splitMessages(strict, lenient, named map[string]bool) map[string]bool {
	taken := p.takenTypeNames()
	split := map[string]bool{}
	collided := map[string]bool{}
	for changed := true; changed; {
		changed = false
		for _, fqn := range sortedKeys(strict) {
			if split[fqn] || collided[fqn] || !p.needsSplit(fqn, lenient, named, split) {
				continue
			}
			msg := p.written[fqn]
			if name := RequiredStructName(msg); taken[name] {
				klog.Warningf("%s already exists, so %s stays optional for every Kind; the judgement queue lists its fields", name, GoNameForProtoMessage(msg))
				collided[fqn] = true
				continue
			}
			split[fqn] = true
			changed = true
		}
	}
	return split
}

// takenTypeNames returns the type names the package has or is about to get.
// A Required name must not collide with one.
func (p *requiredPlanner) takenTypeNames() map[string]bool {
	taken := map[string]bool{}
	for name := range p.byName {
		taken[name] = true
	}
	for _, details := range p.g.outputMessages {
		taken[goNameForOutputProtoMessage(details.Message)] = true
	}
	if p.g.nonAutogenerated != nil {
		for name := range p.g.nonAutogenerated.typeNames {
			taken[name] = true
		}
	}
	for name := range p.g.reservedTypeNames {
		taken[name] = true
	}
	return taken
}

// needsSplit reports whether a strict message needs a Required copy, given
// the messages split so far. A message whose Required copy code already uses
// always does, so that code compiles. Otherwise it needs one only if
// something lenient uses it too and its versions differ: it has a REQUIRED
// field or holds a split message.
func (p *requiredPlanner) needsSplit(fqn string, lenient, named, split map[string]bool) bool {
	if named[fqn] {
		return true
	}
	if !lenient[fqn] {
		return false
	}
	msg := p.written[fqn]
	return hasEmittedRequired(msg, p.g.writeOptions) || p.holdsSplitMessage(msg, split)
}

// holdsSplitMessage reports whether msg's struct holds a split message.
func (p *requiredPlanner) holdsSplitMessage(msg protoreflect.MessageDescriptor, split map[string]bool) bool {
	for _, f := range structFields(msg) {
		if child, ok := specChild(f, p.g.writeOptions); ok && split[string(child.FullName())] {
			return true
		}
	}
	return false
}

// declaredByHand reports whether a hand-written file of the package declares
// the type name.
func (g *TypeGenerator) declaredByHand(name string) bool {
	return g.nonAutogenerated != nil && g.nonAutogenerated.typeNames[name]
}

// taggedByHand reports whether a hand-written type of the package has a
// +kcc:proto tag for the message.
func (g *TypeGenerator) taggedByHand(fqn string) bool {
	return g.nonAutogenerated != nil && g.nonAutogenerated.protoTagged[fqn]
}

// messagesToWrite returns, by full name, the messages WriteVisitedMessages
// writes a plain struct for. It skips the same ones: map entries, and
// messages declared by hand or that a Kind will declare.
func (g *TypeGenerator) messagesToWrite() map[string]protoreflect.MessageDescriptor {
	out := map[string]protoreflect.MessageDescriptor{}
	for _, msg := range deduplicateAndSort(g.visitedMessages) {
		if msg.IsMapEntry() {
			continue
		}
		fqn := string(msg.FullName())
		goName := GoNameForProtoMessage(msg)
		if g.declaredByHand(goName) || g.taggedByHand(fqn) || g.reservedTypeNames[goName] {
			continue
		}
		out[fqn] = msg
	}
	return out
}

// structOptions returns the options for msg's plain struct, and whether a
// strict <Name>Required copy follows it. Without a plan, every struct uses
// the generator's options, as before.
func (g *TypeGenerator) structOptions(fqn string) (WriteOptions, bool) {
	p := g.requiredPlan
	if p == nil {
		return g.writeOptions, false
	}
	switch {
	case p.split[fqn]:
		return g.lenientWriteOptions(), true
	case p.strict[fqn] && !p.lenient[fqn]:
		return g.StrictWriteOptions(), false
	default:
		return g.lenientWriteOptions(), false
	}
}

// lenientWriteOptions are the options for a struct that keeps every field
// optional.
func (g *TypeGenerator) lenientWriteOptions() WriteOptions {
	opts := g.writeOptions
	opts.EmitRequired = false
	opts.RequiredStructs = nil
	return opts
}

// StrictWriteOptions are the options for a struct that enforces the proto's
// REQUIRED fields: the Spec of a new, opted-in Kind, or a nested struct that
// only opted-in Kinds use. A field whose message is split holds the Required
// copy.
func (g *TypeGenerator) StrictWriteOptions() WriteOptions {
	opts := g.writeOptions
	if g.requiredPlan != nil {
		opts.RequiredStructs = g.requiredPlan.split
	}
	return opts
}

// specChild returns the message whose struct a spec field holds: its own
// message, or the value message of a map. It returns false if the field
// holds no generated struct.
func specChild(f protoreflect.FieldDescriptor, opts WriteOptions) (protoreflect.MessageDescriptor, bool) {
	value := f
	if f.IsMap() {
		// GoTypeForField writes only string-keyed maps of messages, and only
		// with EmitMessageMaps.
		if !opts.EmitMessageMaps || f.MapKey().Kind() != protoreflect.StringKind {
			return nil, false
		}
		value = f.MapValue()
	}
	if value.Kind() != protoreflect.MessageKind || !MapsToGoStruct(value.Message()) {
		return nil, false
	}
	return value.Message(), true
}

// plainChildInStatus returns the message whose plain struct an ObservedState
// field holds, as WriteObservedStateFields writes it.
func plainChildInStatus(f protoreflect.FieldDescriptor, observedStateMessages sets.String, opts WriteOptions) (protoreflect.MessageDescriptor, bool) {
	child, ok := specChild(f, opts)
	if !ok {
		return nil, false
	}
	if !f.IsMap() && observedStateMessages.Has(string(child.FullName())) {
		// This field holds the message's ObservedState struct instead.
		return nil, false
	}
	return child, true
}

// structFields returns the fields of msg except the output-only ones, which
// WriteMessage leaves out of the struct.
func structFields(msg protoreflect.MessageDescriptor) []protoreflect.FieldDescriptor {
	var out []protoreflect.FieldDescriptor
	fields := msg.Fields()
	for i := range fields.Len() {
		if f := fields.Get(i); !IsFieldBehavior(f, annotations.FieldBehavior_OUTPUT_ONLY) {
			out = append(out, f)
		}
	}
	return out
}

// hasEmittedRequired reports whether WriteField would put +required on any
// field of msg.
func hasEmittedRequired(msg protoreflect.MessageDescriptor, opts WriteOptions) bool {
	for _, f := range structFields(msg) {
		if !IsFieldBehavior(f, annotations.FieldBehavior_REQUIRED) {
			continue
		}
		if _, err := GoTypeForField(f, false, opts); err == nil {
			return true
		}
	}
	return false
}

func sortedKeys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
