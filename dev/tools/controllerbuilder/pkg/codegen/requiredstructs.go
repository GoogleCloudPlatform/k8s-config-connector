// RequiredFromProtoMarker on a <Kind>Spec opts the Kind in to +required on
// the fields the proto marks REQUIRED.
//
// With --emit-required-from-proto, the scaffold adds it to each new
// <kind>_types.go. Existing Kinds lack it and keep their optional fields,
// since making a field required breaks objects that omit it. To opt in an
// existing Kind, add the marker by hand.
const RequiredFromProtoMarker = "+kcc:required-from-proto"

// IsRequiredFromProtoMarker reports whether a comment line is the marker.
func IsRequiredFromProtoMarker(line string) bool {
	return strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(line), "//")) == RequiredFromProtoMarker
}

// RequiredStructName is the name of msg's Required copy: the plain name plus
// "Required". Opted-in Kinds use the copy when msg has other users.
func RequiredStructName(msg protoreflect.MessageDescriptor) string {
	return GoNameForProtoMessage(msg) + "Required"
}

// specStructName is the struct that a spec field of type msg holds: the
// Required copy if msg is split and the field is in a strict struct, else the
// plain struct.
func specStructName(msg protoreflect.MessageDescriptor, opts WriteOptions) string {
	if opts.RequiredStructs[string(msg.FullName())] {
		return RequiredStructName(msg)
	}
	return GoNameForProtoMessage(msg)
}

// RequiredUses records the hand-written code that uses a package's types.
type RequiredUses struct {
	// MarkedKinds are the Kinds whose Spec has RequiredFromProtoMarker.
	MarkedKinds map[string]bool
	// MarkedSpecs are the opted-in Specs, by type name.
	MarkedSpecs map[string]bool
	// HandWritten maps each type the package declares by hand to the type
	// names its declaration uses.
	HandWritten map[string]map[string]bool
	// FromOtherPackages are the types that other packages under apis/ use.
	FromOtherPackages map[string]bool
}

// ScanRequiredUses reads the hand-written Go files in pkgDir, and the Go files
// of every other package under apisDir that imports importPath. It records
// what each hand-written type uses, so PlanRequiredStructs can follow
// hand-written types.
func ScanRequiredUses(pkgDir, apisDir, importPath string) (*RequiredUses, error) {
	uses := &RequiredUses{
		MarkedKinds:       map[string]bool{},
		MarkedSpecs:       map[string]bool{},
		HandWritten:       map[string]map[string]bool{},
		FromOtherPackages: map[string]bool{},
	}
	if err := uses.scanPackage(pkgDir); err != nil {
		return nil, err
	}
	if apisDir != "" {
		if err := uses.scanImporters(apisDir, pkgDir, importPath); err != nil {
			return nil, err
		}
	}
	return uses, nil
}

func (u *RequiredUses) scanPackage(dir string) error {
	entries, err := os.ReadDir(dir)
	if err != nil {
		if os.IsNotExist(err) {
			// A service generated for the first time has no package yet.
			return nil
		}
		return fmt.Errorf("reading %s: %w", dir, err)
	}
	fset := token.NewFileSet()
	for _, e := range entries {
		// Skip generated files: types.generated.go is about to be rewritten,
		// and deepcopy declares no types. scanNonAutogeneratedTypes uses the
		// same rule.
		if e.IsDir() || !isGoSource(e.Name()) || strings.HasSuffix(e.Name(), "generated.go") || strings.HasPrefix(e.Name(), "zz_generated") {
			continue
		}
		p := filepath.Join(dir, e.Name())
		f, err := parser.ParseFile(fset, p, nil, parser.ParseComments)
		if err != nil {
			return fmt.Errorf("parsing %s: %w", p, err)
		}
		for _, decl := range f.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, spec := range gd.Specs {
				ts, ok := spec.(*ast.TypeSpec)
				if !ok {
					continue
				}
				doc := ts.Doc
				if doc == nil && len(gd.Specs) == 1 {
					doc = gd.Doc
				}
				if kind, ok := strings.CutSuffix(ts.Name.Name, "Spec"); ok && kind != "" && hasRequiredFromProtoMarker(doc) {
					u.MarkedKinds[kind] = true
					u.MarkedSpecs[ts.Name.Name] = true
				}
				used := map[string]bool{}
				collectTypeRefs(ts.Type, used)
				u.HandWritten[ts.Name.Name] = used
			}
		}
	}
	return nil
}

// scanImporters records which of the package's types other packages under
// apisDir use, such as a v1alpha1 Spec that holds a v1beta1 struct. The
// generator can't see those uses any other way.
func (u *RequiredUses) scanImporters(apisDir, pkgDir, importPath string) error {
	quoted := []byte(strconv.Quote(importPath))
	skip := filepath.Clean(pkgDir)
	fset := token.NewFileSet()
	err := filepath.WalkDir(apisDir, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if filepath.Clean(p) == skip {
				return filepath.SkipDir
			}
			return nil
		}
		if !isGoSource(d.Name()) || strings.HasPrefix(d.Name(), "zz_generated") {
			return nil
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		if !bytes.Contains(b, quoted) {
			return nil
		}
		f, err := parser.ParseFile(fset, p, b, 0)
		if err != nil {
			return fmt.Errorf("parsing %s: %w", p, err)
		}
		alias := importName(f, importPath)
		if alias == "" {
			return nil
		}
		ast.Inspect(f, func(n ast.Node) bool {
			if sel, ok := n.(*ast.SelectorExpr); ok {
				if id, ok := sel.X.(*ast.Ident); ok && id.Name == alias {
					u.FromOtherPackages[sel.Sel.Name] = true
				}
			}
			return true
		})
		return nil
	})
	if os.IsNotExist(err) {
		return nil
	}
	return err
}

func isGoSource(name string) bool {
	return strings.HasSuffix(name, ".go") && !strings.HasSuffix(name, "_test.go")
}

// importName returns the name a file uses for importPath, or "" if the file
// doesn't import it by name.
func importName(f *ast.File, importPath string) string {
	for _, imp := range f.Imports {
		p, err := strconv.Unquote(imp.Path.Value)
		if err != nil || p != importPath {
			continue
		}
		if imp.Name == nil {
			return path.Base(importPath)
		}
		if imp.Name.Name == "_" || imp.Name.Name == "." {
			return ""
		}
		return imp.Name.Name
	}
	return ""
}

func hasRequiredFromProtoMarker(doc *ast.CommentGroup) bool {
	if doc == nil {
		return false
	}
	for _, c := range doc.List {
		if IsRequiredFromProtoMarker(c.Text) {
			return true
		}
	}
	return false
}

// collectTypeRefs adds each type name in a type expression to refs, skipping
// types from other packages.
func collectTypeRefs(expr ast.Expr, refs map[string]bool) {
	switch t := expr.(type) {
	case *ast.Ident:
		refs[t.Name] = true
	case *ast.StarExpr:
		collectTypeRefs(t.X, refs)
	case *ast.ArrayType:
		collectTypeRefs(t.Elt, refs)
	case *ast.MapType:
		collectTypeRefs(t.Key, refs)
		collectTypeRefs(t.Value, refs)
	case *ast.ParenExpr:
		collectTypeRefs(t.X, refs)
	case *ast.StructType:
		for _, f := range t.Fields.List {
			collectTypeRefs(f.Type, refs)
		}
	}
}

// requiredPlan says which structs WriteVisitedMessages writes for each
// message. Keys are full proto names.
type requiredPlan struct {
	// strict holds the messages an opted-in Spec reaches. Their struct gets
	// +required markers.
	strict map[string]bool
	// lenient holds the messages anything else reaches. Their struct keeps
	// every field optional.
	lenient map[string]bool
	// split holds the messages in both sets whose two versions differ. Each
	// gets a lenient plain struct and a strict <Name>Required copy.
	split map[string]bool
}

// PlanRequiredStructs decides which structs get +required markers. Call it
// after VisitProto and before WriteVisitedMessages.
//
// A message reached from an opted-in Spec gets a strict struct. A message
// reached from anything else gets a lenient one: a Kind, a status, an
// unmarked Spec or another package. Both walks follow hand-written types, so a
// struct that only opted-in Kinds reach is strict even through a hand-written
// helper. A message that needs both keeps its plain name lenient, so its
// current users don't change, and gets a strict <Name>Required copy. A copy
// that code already uses is always written.
//
// newSpecFields are the top-level Spec fields of the Kinds this run
// scaffolds. Those Kinds get the marker, so their fields are strict uses.
func (g *TypeGenerator) PlanRequiredStructs(uses *RequiredUses, newSpecFields []protoreflect.FieldDescriptor) {
	if uses == nil {
		uses = &RequiredUses{}
	}
	written := g.messagesToWrite()
	byName := map[string]string{}
	byRequiredName := map[string]string{}
	for fqn, msg := range written {
		byName[GoNameForProtoMessage(msg)] = fqn
		byRequiredName[RequiredStructName(msg)] = fqn
	}

	// The walks visit generated messages, as "msg:<full name>", and types
	// declared by hand, as "go:<name>". A generated field reaches a
	// hand-written type when that type stands in for the field's message.
	msgNode := func(fqn string) string { return "msg:" + fqn }
	goNode := func(name string) string { return "go:" + name }
	// typeNode is the node a type name refers to, or "" for a name that is
	// neither, such as string.
	typeNode := func(name string) string {
		if fqn, ok := byName[name]; ok {
			return msgNode(fqn)
		}
		if _, ok := uses.HandWritten[name]; ok {
			return goNode(name)
		}
		return ""
	}
	// fieldNode is the node for the struct a field holds.
	fieldNode := func(f protoreflect.FieldDescriptor, fqn string) string {
		if written[fqn] != nil {
			return msgNode(fqn)
		}
		return typeNode(GoNameForProtoMessage(childMessage(f)))
	}
	next := func(node string) []string {
		var out []string
		if name, ok := strings.CutPrefix(node, "go:"); ok {
			for _, used := range sortedKeys(uses.HandWritten[name]) {
				if n := typeNode(used); n != "" {
					out = append(out, n)
				}
			}
			return out
		}
		msg := written[strings.TrimPrefix(node, "msg:")]
		for i := 0; i < msg.Fields().Len(); i++ {
			f := msg.Fields().Get(i)
			if IsFieldBehavior(f, annotations.FieldBehavior_OUTPUT_ONLY) {
				// WriteMessage leaves these out of the struct.
				continue
			}
			if fqn, ok := specChild(f, g.writeOptions); ok {
				if n := fieldNode(f, fqn); n != "" {
					out = append(out, n)
				}
			}
		}
		return out
	}
	walk := func(seeds []string, stop func(string) bool) map[string]bool {
		reached := map[string]bool{}
		queue := append([]string(nil), seeds...)
		for len(queue) > 0 {
			n := queue[0]
			queue = queue[1:]
			if n == "" || reached[n] || stop(n) {
				continue
			}
			reached[n] = true
			queue = append(queue, next(n)...)
		}
		return reached
	}

	// Code that uses a Required copy needs it, wherever that code is.
	named := map[string]bool{}
	var strictSeeds []string
	used := map[string]bool{}
	for _, names := range uses.HandWritten {
		for name := range names {
			used[name] = true
		}
	}
	for name := range uses.FromOtherPackages {
		used[name] = true
	}
	for _, name := range sortedKeys(used) {
		// Check message names first: a message can be called FooRequired
		// without being Foo's copy.
		if _, ok := byName[name]; ok {
			continue
		}
		if fqn, ok := byRequiredName[name]; ok && !g.declaredByHand(name) {
			named[fqn] = true
			strictSeeds = append(strictSeeds, msgNode(fqn))
		}
	}
	for _, name := range sortedKeys(uses.MarkedSpecs) {
		strictSeeds = append(strictSeeds, goNode(name))
	}
	for _, f := range newSpecFields {
		if fqn, ok := specChild(f, g.writeOptions); ok {
			strictSeeds = append(strictSeeds, fieldNode(f, fqn))
		}
	}
	strictReached := walk(strictSeeds, func(string) bool { return false })

	// Every other hand-written type starts a lenient walk: a Kind, a status,
	// an unmarked Spec, or a type nothing uses. A type that only opted-in
	// Specs reach doesn't, so what it holds stays strict. The walk stops at
	// opted-in Specs, so a Kind that holds its own Spec doesn't make it
	// lenient.
	var lenientSeeds []string
	for _, name := range sortedKeys(uses.HandWritten) {
		if !uses.MarkedSpecs[name] && !strictReached[goNode(name)] {
			lenientSeeds = append(lenientSeeds, goNode(name))
		}
	}
	for _, name := range sortedKeys(uses.FromOtherPackages) {
		lenientSeeds = append(lenientSeeds, typeNode(name))
	}
	// An ObservedState struct holds a message's plain struct when the message
	// has no ObservedState struct of its own, and for map values. Those must
	// stay lenient, or +required ends up in the status schema.
	for _, details := range g.outputMessages {
		for _, f := range details.OutputFields {
			if fqn, ok := plainChildInStatus(f, g.observedStateMessages, g.writeOptions); ok {
				lenientSeeds = append(lenientSeeds, fieldNode(f, fqn))
			}
		}
	}
	lenientReached := walk(lenientSeeds, func(n string) bool {
		name, ok := strings.CutPrefix(n, "go:")
		return ok && uses.MarkedSpecs[name]
	})

	strict := map[string]bool{}
	for n := range strictReached {
		if fqn, ok := strings.CutPrefix(n, "msg:"); ok {
			strict[fqn] = true
		}
	}
	lenient := map[string]bool{}
	for n := range lenientReached {
		if fqn, ok := strings.CutPrefix(n, "msg:"); ok {
			lenient[fqn] = true
		}
	}

	children := func(fqn string) []string {
		msg := written[fqn]
		var out []string
		for i := 0; i < msg.Fields().Len(); i++ {
			f := msg.Fields().Get(i)
			if IsFieldBehavior(f, annotations.FieldBehavior_OUTPUT_ONLY) {
				// WriteMessage leaves these out of the struct.
				continue
			}
			if child, ok := specChild(f, g.writeOptions); ok && written[child] != nil {
				out = append(out, child)
			}
		}
		return out
	}

	// The Required name must not collide with a type the package has or is
	// about to get.
	taken := map[string]bool{}
	for _, msg := range written {
		taken[GoNameForProtoMessage(msg)] = true
	}
	for _, details := range g.outputMessages {
		taken[goNameForOutputProtoMessage(details.Message)] = true
	}
	if g.nonAutogenerated != nil {
		for name := range g.nonAutogenerated.typeNames {
			taken[name] = true
		}
	}
	for name := range g.reservedTypeNames {
		taken[name] = true
	}

	// A message needs two structs only if its versions differ: it has a
	// REQUIRED field or holds a split message. Splitting a message can make its
	// parents differ too, including through cycles, so loop until nothing
	// changes. A message whose Required copy code already uses is always split,
	// so that code compiles.
	split := map[string]bool{}
	collided := map[string]bool{}
	for changed := true; changed; {
		changed = false
		for _, fqn := range sortedKeys(strict) {
			if split[fqn] || collided[fqn] {
				continue
			}
			msg := written[fqn]
			if !named[fqn] {
				if !lenient[fqn] {
					continue
				}
				differs := hasEmittedRequired(msg, g.writeOptions)
				for _, child := range children(fqn) {
					differs = differs || split[child]
				}
				if !differs {
					continue
				}
			}
			if name := RequiredStructName(msg); taken[name] {
				klog.Warningf("%s already exists, so %s stays optional for every Kind; the judgement queue lists its fields", name, GoNameForProtoMessage(msg))
				collided[fqn] = true
				continue
			}
			split[fqn] = true
			changed = true
		}
	}

	g.requiredPlan = &requiredPlan{strict: strict, lenient: lenient, split: split}
}

// declaredByHand reports whether a hand-written file of the package declares
// the type name.
func (g *TypeGenerator) declaredByHand(name string) bool {
	return g.nonAutogenerated != nil && g.nonAutogenerated.typeNames[name]
}

// messagesToWrite returns, by full name, the messages WriteVisitedMessages
// writes a plain struct for. It skips the same ones: map entries, and
// messages declared by hand or that a Kind will declare.
func (g *TypeGenerator) messagesToWrite() map[string]protoreflect.MessageDescriptor {
	out := map[string]protoreflect.MessageDescriptor{}
	for _, msg := range deduplicateAndSort(g.visitedMessages) {
		if msg.IsMapEntry() {
			continue
		}
		fqn := string(msg.FullName())
		goName := GoNameForProtoMessage(msg)
		if g.nonAutogenerated != nil && (g.nonAutogenerated.typeNames[goName] || g.nonAutogenerated.protoTagged[fqn]) {
			continue
		}
		if g.reservedTypeNames[goName] {
			continue
		}
		out[fqn] = msg
	}
	return out
}

// structOptions returns the options for msg's plain struct, and whether a
// strict <Name>Required copy follows it. Without a plan, every struct uses
// the generator's options, as before.
func (g *TypeGenerator) structOptions(fqn string) (WriteOptions, bool) {
	p := g.requiredPlan
	if p == nil {
		return g.writeOptions, false
	}
	switch {
	case p.split[fqn]:
		return g.lenientWriteOptions(), true
	case p.strict[fqn] && !p.lenient[fqn]:
		return g.StrictWriteOptions(), false
	default:
		return g.lenientWriteOptions(), false
	}
}

// lenientWriteOptions are the options for a struct that keeps every field
// optional.
func (g *TypeGenerator) lenientWriteOptions() WriteOptions {
	opts := g.writeOptions
	opts.EmitRequired = false
	opts.RequiredStructs = nil
	return opts
}

// StrictWriteOptions are the options for a struct that enforces the proto's
// REQUIRED fields: the Spec of a new, opted-in Kind, or a nested struct that
// only opted-in Kinds reach. A field whose message is split holds the
// Required copy.
func (g *TypeGenerator) StrictWriteOptions() WriteOptions {
	opts := g.writeOptions
	if g.requiredPlan != nil {
		opts.RequiredStructs = g.requiredPlan.split
	}
	return opts
}

// specChild returns the message whose struct a spec field holds: its own
// message, or the value message of a map. It returns false if the field
// holds no generated struct.
func specChild(f protoreflect.FieldDescriptor, opts WriteOptions) (string, bool) {
	if f.IsMap() {
		// GoTypeForField writes only string-keyed maps of messages, and only
		// with EmitMessageMaps.
		if !opts.EmitMessageMaps || f.MapKey().Kind() != protoreflect.StringKind {
			return "", false
		}
		value := f.MapValue()
		if value.Kind() != protoreflect.MessageKind || !MapsToGoStruct(value.Message()) {
			return "", false
		}
		return string(value.Message().FullName()), true
	}
	if f.Kind() != protoreflect.MessageKind || !MapsToGoStruct(f.Message()) {
		return "", false
	}
	return string(f.Message().FullName()), true
}

// childMessage returns the message whose struct a field holds: its own
// message, or the value message of a map. Call it only for a field that
// specChild accepts.
func childMessage(f protoreflect.FieldDescriptor) protoreflect.MessageDescriptor {
	if f.IsMap() {
		return f.MapValue().Message()
	}
	return f.Message()
}

// plainChildInStatus returns the message whose plain struct an ObservedState
// field holds, as WriteObservedStateFields writes it.
func plainChildInStatus(f protoreflect.FieldDescriptor, observedStateMessages sets.String, opts WriteOptions) (string, bool) {
	fqn, ok := specChild(f, opts)
	if !ok {
		return "", false
	}
	if !f.IsMap() && observedStateMessages.Has(fqn) {
		// This field holds the message's ObservedState struct instead.
		return "", false
	}
	return fqn, true
}

// hasEmittedRequired reports whether WriteField would put +required on any
// field of msg.
func hasEmittedRequired(msg protoreflect.MessageDescriptor, opts WriteOptions) bool {
	for i := 0; i < msg.Fields().Len(); i++ {
		f := msg.Fields().Get(i)
		if !IsFieldBehavior(f, annotations.FieldBehavior_REQUIRED) || IsFieldBehavior(f, annotations.FieldBehavior_OUTPUT_ONLY) {
			continue
		}
		if _, err := GoTypeForField(f, false, opts); err == nil {
			return true
		}
	}
	return false
}

func sortedKeys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
