// RequiredFromProtoMarker on a <Kind>Spec says the Kind enforces the fields
// the proto marks REQUIRED.
//
// With --emit-required-from-proto, the scaffold writes it into every new
// <kind>_types.go, and only the Kinds that have it get +required markers. A
// Kind without it keeps its types as they are: making an optional field
// required breaks the objects that leave the field out. Adding the marker to
// an existing Kind by hand is how someone decides to tighten it.
const RequiredFromProtoMarker = "+kcc:required-from-proto"

// IsRequiredFromProtoMarker reports whether a comment line is the marker.
func IsRequiredFromProtoMarker(line string) bool {
	return strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(line), "//")) == RequiredFromProtoMarker
}

// RequiredStructName is the struct a Kind with the marker uses for msg when
// Kinds without it use msg too: the plain name plus "Required".
func RequiredStructName(msg protoreflect.MessageDescriptor) string {
	return GoNameForProtoMessage(msg) + "Required"
}

// specStructName is the struct a spec field of msg's type holds: the Required
// struct when msg is split and the field is in a strict struct, the plain one
// otherwise.
func specStructName(msg protoreflect.MessageDescriptor, opts WriteOptions) string {
	if opts.RequiredStructs[string(msg.FullName())] {
		return RequiredStructName(msg)
	}
	return GoNameForProtoMessage(msg)
}

// RequiredUses records which types of a package are used by code the
// generator does not write, and from where.
type RequiredUses struct {
	// MarkedKinds are the Kinds whose Spec carries RequiredFromProtoMarker.
	MarkedKinds map[string]bool
	// FromMarkedSpecs are the type names a marked Spec uses directly.
	FromMarkedSpecs map[string]bool
	// FromElsewhere are the type names used anywhere else: the Spec of a Kind
	// without the marker, a status struct, a hand-written helper type, or a
	// type in another package under apis/.
	FromElsewhere map[string]bool
}

// ScanRequiredUses reads the hand-written Go files in pkgDir, and the Go files
// of every other package under apisDir that imports importPath.
//
// Only a marked Spec's own fields count as strict uses. A hand-written helper
// type counts as a use from elsewhere even when a marked Spec reaches it,
// because the scan does not follow hand-written types. That errs towards
// leaving a field optional, which the judgement queue then reports.
func ScanRequiredUses(pkgDir, apisDir, importPath string) (*RequiredUses, error) {
	uses := &RequiredUses{
		MarkedKinds:     map[string]bool{},
		FromMarkedSpecs: map[string]bool{},
		FromElsewhere:   map[string]bool{},
	}
	if err := uses.scanPackage(pkgDir); err != nil {
		return nil, err
	}
	if apisDir != "" {
		if err := uses.scanImporters(apisDir, pkgDir, importPath); err != nil {
			return nil, err
		}
	}
	return uses, nil
}

func (u *RequiredUses) scanPackage(dir string) error {
	entries, err := os.ReadDir(dir)
	if err != nil {
		if os.IsNotExist(err) {
			// A service generated for the first time has no package yet.
			return nil
		}
		return fmt.Errorf("reading %s: %w", dir, err)
	}
	fset := token.NewFileSet()
	for _, e := range entries {
		// The generated files are left out: types.generated.go is about to be
		// rewritten from the proto, and deepcopy declares no types. The rule
		// matches scanNonAutogeneratedTypes.
		if e.IsDir() || !isGoSource(e.Name()) || strings.HasSuffix(e.Name(), "generated.go") || strings.HasPrefix(e.Name(), "zz_generated") {
			continue
		}
		p := filepath.Join(dir, e.Name())
		f, err := parser.ParseFile(fset, p, nil, parser.ParseComments)
		if err != nil {
			return fmt.Errorf("parsing %s: %w", p, err)
		}
		for _, decl := range f.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, spec := range gd.Specs {
				ts, ok := spec.(*ast.TypeSpec)
				if !ok {
					continue
				}
				doc := ts.Doc
				if doc == nil && len(gd.Specs) == 1 {
					doc = gd.Doc
				}
				into := u.FromElsewhere
				if kind, ok := strings.CutSuffix(ts.Name.Name, "Spec"); ok && kind != "" && hasRequiredFromProtoMarker(doc) {
					u.MarkedKinds[kind] = true
					into = u.FromMarkedSpecs
				}
				collectTypeRefs(ts.Type, into)
			}
		}
	}
	return nil
}

// scanImporters records every type of the package that another package under
// apisDir names, such as a v1alpha1 Spec holding a v1beta1 struct. The
// generator cannot see those uses any other way.
func (u *RequiredUses) scanImporters(apisDir, pkgDir, importPath string) error {
	quoted := []byte(strconv.Quote(importPath))
	skip := filepath.Clean(pkgDir)
	fset := token.NewFileSet()
	err := filepath.WalkDir(apisDir, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if filepath.Clean(p) == skip {
				return filepath.SkipDir
			}
			return nil
		}
		if !isGoSource(d.Name()) || strings.HasPrefix(d.Name(), "zz_generated") {
			return nil
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		if !bytes.Contains(b, quoted) {
			return nil
		}
		f, err := parser.ParseFile(fset, p, b, 0)
		if err != nil {
			return fmt.Errorf("parsing %s: %w", p, err)
		}
		alias := importName(f, importPath)
		if alias == "" {
			return nil
		}
		ast.Inspect(f, func(n ast.Node) bool {
			if sel, ok := n.(*ast.SelectorExpr); ok {
				if id, ok := sel.X.(*ast.Ident); ok && id.Name == alias {
					u.FromElsewhere[sel.Sel.Name] = true
				}
			}
			return true
		})
		return nil
	})
	if os.IsNotExist(err) {
		return nil
	}
	return err
}

func isGoSource(name string) bool {
	return strings.HasSuffix(name, ".go") && !strings.HasSuffix(name, "_test.go")
}

// importName is the name a file uses for importPath, or "" if the file does
// not import it under a name.
func importName(f *ast.File, importPath string) string {
	for _, imp := range f.Imports {
		p, err := strconv.Unquote(imp.Path.Value)
		if err != nil || p != importPath {
			continue
		}
		if imp.Name == nil {
			return path.Base(importPath)
		}
		if imp.Name.Name == "_" || imp.Name.Name == "." {
			return ""
		}
		return imp.Name.Name
	}
	return ""
}

func hasRequiredFromProtoMarker(doc *ast.CommentGroup) bool {
	if doc == nil {
		return false
	}
	for _, c := range doc.List {
		if IsRequiredFromProtoMarker(c.Text) {
			return true
		}
	}
	return false
}

// collectTypeRefs adds every unqualified type name in a type expression to
// refs. Names from other packages are left out.
func collectTypeRefs(expr ast.Expr, refs map[string]bool) {
	switch t := expr.(type) {
	case *ast.Ident:
		refs[t.Name] = true
	case *ast.StarExpr:
		collectTypeRefs(t.X, refs)
	case *ast.ArrayType:
		collectTypeRefs(t.Elt, refs)
	case *ast.MapType:
		collectTypeRefs(t.Key, refs)
		collectTypeRefs(t.Value, refs)
	case *ast.ParenExpr:
		collectTypeRefs(t.X, refs)
	case *ast.StructType:
		for _, f := range t.Fields.List {
			collectTypeRefs(f.Type, refs)
		}
	}
}

// requiredPlan says which structs WriteVisitedMessages writes for each
// message. Keys are full proto names.
type requiredPlan struct {
	// strict holds the messages a marked Spec reaches. Their struct carries
	// +required markers.
	strict map[string]bool
	// lenient holds the messages anything else reaches. Their struct leaves
	// every field optional.
	lenient map[string]bool
	// split holds the messages in both sets whose two structs differ. Each
	// gets its plain struct, lenient, and a <Name>Required struct, strict.
	split map[string]bool
}

// PlanRequiredStructs decides which structs carry +required markers. Call it
// after VisitProto and before WriteVisitedMessages.
//
// A message reached from the Spec of a Kind with RequiredFromProtoMarker gets
// a strict struct. A message reached from anything else gets a lenient one:
// the Spec of a Kind without the marker, a status struct, a hand-written type
// or another package. A message that needs both keeps its plain name for the
// lenient struct, so nothing that uses it changes, and gets the strict struct
// beside it as <Name>Required. Code that names <Name>Required always gets it.
//
// newSpecFields are the top-level Spec fields of the Kinds this run
// scaffolds. Those Kinds get the marker, so their fields are strict uses.
func (g *TypeGenerator) PlanRequiredStructs(uses *RequiredUses, newSpecFields []protoreflect.FieldDescriptor) {
	written := g.messagesToWrite()
	byName := map[string]string{}
	byRequiredName := map[string]string{}
	for fqn, msg := range written {
		byName[GoNameForProtoMessage(msg)] = fqn
		byRequiredName[RequiredStructName(msg)] = fqn
	}

	strict := map[string]bool{}
	lenient := map[string]bool{}
	// named holds the messages whose Required struct some code names. That
	// code does not compile unless the struct is written.
	named := map[string]bool{}
	use := func(typeName string, fromMarkedSpec bool) {
		// A message's own name comes first: a message can be called
		// FooRequired without being Foo's copy.
		if fqn, ok := byName[typeName]; ok {
			if fromMarkedSpec {
				strict[fqn] = true
			} else {
				lenient[fqn] = true
			}
			return
		}
		if fqn, ok := byRequiredName[typeName]; ok && !g.declaredByHand(typeName) {
			// Code that names the Required struct wants it, wherever it is.
			strict[fqn] = true
			named[fqn] = true
		}
	}
	if uses != nil {
		for _, name := range sortedKeys(uses.FromMarkedSpecs) {
			use(name, true)
		}
		for _, name := range sortedKeys(uses.FromElsewhere) {
			use(name, false)
		}
	}
	for _, f := range newSpecFields {
		if fqn, ok := specChild(f, g.writeOptions); ok && written[fqn] != nil {
			strict[fqn] = true
		}
	}
	// An ObservedState struct holds the plain struct of a message that needs
	// no ObservedState struct of its own, and of a map's values. Those must
	// stay lenient, or +required ends up in the status schema.
	for _, details := range g.outputMessages {
		for _, f := range details.OutputFields {
			if fqn, ok := plainChildInStatus(f, g.observedStateMessages, g.writeOptions); ok && written[fqn] != nil {
				lenient[fqn] = true
			}
		}
	}

	children := func(fqn string) []string {
		msg := written[fqn]
		var out []string
		for i := 0; i < msg.Fields().Len(); i++ {
			f := msg.Fields().Get(i)
			if IsFieldBehavior(f, annotations.FieldBehavior_OUTPUT_ONLY) {
				// WriteMessage leaves these out of the struct.
				continue
			}
			if child, ok := specChild(f, g.writeOptions); ok && written[child] != nil {
				out = append(out, child)
			}
		}
		return out
	}
	closeOver(strict, children)
	closeOver(lenient, children)

	// The Required name must not collide with a type the package has or is
	// about to get.
	taken := map[string]bool{}
	for _, msg := range written {
		taken[GoNameForProtoMessage(msg)] = true
	}
	for _, details := range g.outputMessages {
		taken[goNameForOutputProtoMessage(details.Message)] = true
	}
	if g.nonAutogenerated != nil {
		for name := range g.nonAutogenerated.typeNames {
			taken[name] = true
		}
	}
	for name := range g.reservedTypeNames {
		taken[name] = true
	}

	// A message whose strict and lenient structs would be the same needs only
	// one. They differ when the message has a REQUIRED field, or holds a
	// message that is split. The loop runs until nothing changes, because a
	// split can make its parent differ too, cycles included. A message whose
	// Required struct is named is always split, so that code compiles.
	split := map[string]bool{}
	collided := map[string]bool{}
	for changed := true; changed; {
		changed = false
		for _, fqn := range sortedKeys(strict) {
			if split[fqn] || collided[fqn] {
				continue
			}
			msg := written[fqn]
			if !named[fqn] {
				if !lenient[fqn] {
					continue
				}
				differs := hasEmittedRequired(msg, g.writeOptions)
				for _, child := range children(fqn) {
					differs = differs || split[child]
				}
				if !differs {
					continue
				}
			}
			if name := RequiredStructName(msg); taken[name] {
				klog.Warningf("%s is already declared, so %s stays optional for every Kind; the judgement queue lists the fields", name, GoNameForProtoMessage(msg))
				collided[fqn] = true
				continue
			}
			split[fqn] = true
			changed = true
		}
	}

	g.requiredPlan = &requiredPlan{strict: strict, lenient: lenient, split: split}
}

// declaredByHand reports whether a hand-written file of the package declares
// the type name.
func (g *TypeGenerator) declaredByHand(name string) bool {
	return g.nonAutogenerated != nil && g.nonAutogenerated.typeNames[name]
}

// messagesToWrite returns the messages WriteVisitedMessages writes a plain
// struct for, by full name. It skips the same messages: map entries, and
// messages the package already declares by hand or a Kind will declare.
func (g *TypeGenerator) messagesToWrite() map[string]protoreflect.MessageDescriptor {
	out := map[string]protoreflect.MessageDescriptor{}
	for _, msg := range deduplicateAndSort(g.visitedMessages) {
		if msg.IsMapEntry() {
			continue
		}
		fqn := string(msg.FullName())
		goName := GoNameForProtoMessage(msg)
		if g.nonAutogenerated != nil && (g.nonAutogenerated.typeNames[goName] || g.nonAutogenerated.protoTagged[fqn]) {
			continue
		}
		if g.reservedTypeNames[goName] {
			continue
		}
		out[fqn] = msg
	}
	return out
}

// structOptions returns the options for msg's plain struct, and whether a
// strict <Name>Required struct follows it. Without a plan, every struct is
// written with the generator's options, as before.
func (g *TypeGenerator) structOptions(fqn string) (WriteOptions, bool) {
	p := g.requiredPlan
	if p == nil {
		return g.writeOptions, false
	}
	switch {
	case p.split[fqn]:
		return g.lenientWriteOptions(), true
	case p.strict[fqn] && !p.lenient[fqn]:
		return g.StrictWriteOptions(), false
	default:
		return g.lenientWriteOptions(), false
	}
}

// lenientWriteOptions are the options for a struct that leaves every field
// optional.
func (g *TypeGenerator) lenientWriteOptions() WriteOptions {
	opts := g.writeOptions
	opts.EmitRequired = false
	opts.RequiredStructs = nil
	return opts
}

// StrictWriteOptions are the options for a struct that enforces the proto's
// REQUIRED fields: a Spec scaffolded for a Kind with the marker, or a nested
// struct only such Kinds reach. A field whose message is split holds the
// Required struct.
func (g *TypeGenerator) StrictWriteOptions() WriteOptions {
	opts := g.writeOptions
	if g.requiredPlan != nil {
		opts.RequiredStructs = g.requiredPlan.split
	}
	return opts
}

// specChild returns the message whose struct a spec field holds: the field's
// own message, or a map's value message. It reports false for a field that
// holds no generated struct.
func specChild(f protoreflect.FieldDescriptor, opts WriteOptions) (string, bool) {
	if f.IsMap() {
		// GoTypeForField writes only string-keyed maps of messages, and only
		// with EmitMessageMaps.
		if !opts.EmitMessageMaps || f.MapKey().Kind() != protoreflect.StringKind {
			return "", false
		}
		value := f.MapValue()
		if value.Kind() != protoreflect.MessageKind || !MapsToGoStruct(value.Message()) {
			return "", false
		}
		return string(value.Message().FullName()), true
	}
	if f.Kind() != protoreflect.MessageKind || !MapsToGoStruct(f.Message()) {
		return "", false
	}
	return string(f.Message().FullName()), true
}

// plainChildInStatus returns the message whose plain struct an ObservedState
// field holds, the way WriteObservedStateFields writes it.
func plainChildInStatus(f protoreflect.FieldDescriptor, observedStateMessages sets.String, opts WriteOptions) (string, bool) {
	fqn, ok := specChild(f, opts)
	if !ok {
		return "", false
	}
	if !f.IsMap() && observedStateMessages.Has(fqn) {
		// This field holds the message's ObservedState struct instead.
		return "", false
	}
	return fqn, true
}

// hasEmittedRequired reports whether WriteField would put +required on any
// field of msg.
func hasEmittedRequired(msg protoreflect.MessageDescriptor, opts WriteOptions) bool {
	for i := 0; i < msg.Fields().Len(); i++ {
		f := msg.Fields().Get(i)
		if !IsFieldBehavior(f, annotations.FieldBehavior_REQUIRED) || IsFieldBehavior(f, annotations.FieldBehavior_OUTPUT_ONLY) {
			continue
		}
		if _, err := GoTypeForField(f, false, opts); err == nil {
			return true
		}
	}
	return false
}

// closeOver adds to set everything reachable from it through children.
func closeOver(set map[string]bool, children func(string) []string) {
	queue := sortedKeys(set)
	for len(queue) > 0 {
		fqn := queue[0]
		queue = queue[1:]
		for _, child := range children(fqn) {
			if !set[child] {
				set[child] = true
				queue = append(queue, child)
			}
		}
	}
}

func sortedKeys(m map[string]bool) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
