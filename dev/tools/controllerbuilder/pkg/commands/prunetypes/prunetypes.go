type PruneTypesOptions struct {
	*options.GenerateOptions
	Target string
}

func (o *PruneTypesOptions) BindFlags(cmd *cobra.Command) {
	cmd.Flags().StringVar(&o.Target, "target", o.Target, "target file or package directory to prune (e.g. apis/clouddeploy/v1alpha1/types.generated.go)")
}

func BuildCommand(baseOptions *options.GenerateOptions) *cobra.Command {
	opt := &PruneTypesOptions{
		GenerateOptions: baseOptions,
	}

	cmd := &cobra.Command{
		Use:   "prune-types [target]",
		Short: "comment out unreachable types in generated files",
		PreRunE: func(cmd *cobra.Command, args []string) error {
			if len(args) > 0 {
				opt.Target = args[0]
			}
			if opt.Target == "" {
				return fmt.Errorf("target is required (pass file or directory path)")
			}
			return nil
		},
		RunE: func(cmd *cobra.Command, args []string) error {
			ctx := cmd.Context()
			if err := PruneTypes(ctx, opt); err != nil {
				return err
			}
			return nil
		},
	}
	opt.BindFlags(cmd)

	return cmd
}

func isGeneratedFile(filePath string, file *ast.File) bool {
	base := filepath.Base(filePath)
	if strings.Contains(base, ".generated.") || strings.Contains(base, "_generated") || strings.HasPrefix(base, "zz_") {
		return true
	}
	for _, cg := range file.Comments {
		for _, c := range cg.List {
			text := c.Text
			if strings.Contains(text, "//go:build !ignore_autogenerated") ||
				strings.Contains(text, "Code generated by") ||
				strings.Contains(text, "DO NOT EDIT") ||
				strings.Contains(text, "+generated:types") {
				return true
			}
		}
	}
	return false
}

func PruneTypes(ctx context.Context, o *PruneTypesOptions) error {
	stat, err := os.Stat(o.Target)
	if err != nil {
		return fmt.Errorf("stat %s: %w", o.Target, err)
	}

	var pkgDir string
	var targetFiles []string

	if stat.IsDir() {
		pkgDir = o.Target
		entries, err := os.ReadDir(pkgDir)
		if err != nil {
			return fmt.Errorf("reading dir %s: %w", pkgDir, err)
		}
		for _, entry := range entries {
			if entry.IsDir() {
				continue
			}
			name := entry.Name()
			if strings.Contains(name, ".generated.") && strings.HasSuffix(name, ".go") {
				targetFiles = append(targetFiles, filepath.Join(pkgDir, name))
			}
		}
		if len(targetFiles) == 0 {
			return fmt.Errorf("no *.generated.go files found in %s", pkgDir)
		}
	} else {
		pkgDir = filepath.Dir(o.Target)
		targetFiles = []string{o.Target}
	}

	cfg := &packages.Config{
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedCompiledGoFiles | packages.NeedImports | packages.NeedTypes | packages.NeedTypesInfo | packages.NeedSyntax,
		Dir:  pkgDir,
	}
	pkgs, err := packages.Load(cfg, ".")
	if err != nil {
		return fmt.Errorf("loading package %q: %w", pkgDir, err)
	}
	if len(pkgs) == 0 {
		return fmt.Errorf("no packages found in %s", pkgDir)
	}
	pkg := pkgs[0]

	fset := pkg.Fset

	typeToFile := make(map[*types.TypeName]string)
	typeToDecl := make(map[*types.TypeName]*ast.GenDecl)
	fileToTypes := make(map[string][]*types.TypeName)
	typeEdges := make(map[*types.TypeName]map[*types.TypeName]bool)
	handwrittenRefs := make(map[*types.TypeName]bool)

	// Map AST GenDecls to their TypeNames
	for _, astFile := range pkg.Syntax {
		filePath := fset.File(astFile.Pos()).Name()

		for _, decl := range astFile.Decls {
			genDecl, ok := decl.(*ast.GenDecl)
			if !ok || genDecl.Tok != token.TYPE {
				continue
			}
			for _, spec := range genDecl.Specs {
				typeSpec, ok := spec.(*ast.TypeSpec)
				if !ok {
					continue
				}
				obj := pkg.TypesInfo.Defs[typeSpec.Name]
				if typeName, ok := obj.(*types.TypeName); ok {
					typeToFile[typeName] = filePath
					typeToDecl[typeName] = genDecl
					fileToTypes[filePath] = append(fileToTypes[filePath], typeName)
				}
			}
		}
	}

	// Build edges
	for _, astFile := range pkg.Syntax {
		filePath := fset.File(astFile.Pos()).Name()
		isGen := isGeneratedFile(filePath, astFile)

		ast.Inspect(astFile, func(n ast.Node) bool {
			if ident, ok := n.(*ast.Ident); ok {
				if obj := pkg.TypesInfo.Uses[ident]; obj != nil {
					if typeName, ok := obj.(*types.TypeName); ok {
						if typeToFile[typeName] != "" {
							if !isGen {
								handwrittenRefs[typeName] = true
							} else {
								// Find which type declaration this reference is inside
								var parentType *types.TypeName
								// We can determine the parent type by checking if the ident's position is within any typeToDecl
								for tName, decl := range typeToDecl {
									if typeToFile[tName] == filePath && decl.Pos() <= ident.Pos() && ident.Pos() <= decl.End() {
										parentType = tName
										break
									}
								}
								if parentType != nil && parentType != typeName {
									if typeEdges[parentType] == nil {
										typeEdges[parentType] = make(map[*types.TypeName]bool)
									}
									typeEdges[parentType][typeName] = true
								}
							}
						}
					}
				}
			}
			return true
		})
	}

	// Compute reachability using BFS
	reachable := make(map[*types.TypeName]bool)
	var queue []*types.TypeName

	for t, ref := range handwrittenRefs {
		if ref {
			reachable[t] = true
			queue = append(queue, t)
		}
	}

	for len(queue) > 0 {
		curr := queue[0]
		queue = queue[1:]

		for dep := range typeEdges[curr] {
			if !reachable[dep] {
				reachable[dep] = true
				queue = append(queue, dep)
			}
		}
	}

	// Prune unreachable types in target files
	type unreachableDecl struct {
		decl     *ast.GenDecl
		typeName *types.TypeName
	}

	for _, targetFile := range targetFiles {
		var toPrune []unreachableDecl
		for _, typeName := range fileToTypes[targetFile] {
			if !reachable[typeName] {
				toPrune = append(toPrune, unreachableDecl{
					decl:     typeToDecl[typeName],
					typeName: typeName,
				})
			}
		}

		if len(toPrune) == 0 {
			klog.Infof("No unreachable types found in %s", targetFile)
			continue
		}

		sort.Slice(toPrune, func(i, j int) bool {
			posI := toPrune[i].decl.Pos()
			if toPrune[i].decl.Doc != nil {
				posI = toPrune[i].decl.Doc.Pos()
			}
			posJ := toPrune[j].decl.Pos()
			if toPrune[j].decl.Doc != nil {
				posJ = toPrune[j].decl.Doc.Pos()
			}
			return fset.Position(posI).Offset > fset.Position(posJ).Offset
		})

		content, err := os.ReadFile(targetFile)
		if err != nil {
			return fmt.Errorf("reading %s: %w", targetFile, err)
		}

		for _, item := range toPrune {
			startPos := item.decl.Pos()
			if item.decl.Doc != nil {
				startPos = item.decl.Doc.Pos()
			}
			endPos := item.decl.End()

			startOffset := fset.Position(startPos).Offset
			endOffset := fset.Position(endPos).Offset

			origText := string(content[startOffset:endOffset])
			cleanText := strings.ReplaceAll(origText, "*/", "*-/")
			cleanText = strings.ReplaceAll(cleanText, "/*", "/-*")
			replacement := fmt.Sprintf("/* unreachable type %s\n%s\n*/", item.typeName.Name(), cleanText)

			var newContent []byte
			newContent = append(newContent, content[:startOffset]...)
			newContent = append(newContent, []byte(replacement)...)
			newContent = append(newContent, content[endOffset:]...)
			content = newContent

			klog.Infof("Commented out unreachable type %s in %s", item.typeName.Name(), targetFile)
		}

		content, err = dropUnusedImports(targetFile, content)
		if err != nil {
			return fmt.Errorf("dropping unused imports in %s: %w", targetFile, err)
		}

		if err := os.WriteFile(targetFile, content, 0644); err != nil {
			return fmt.Errorf("writing %s: %w", targetFile, err)
		}
	}

	return nil
}

// dropUnusedImports parses the Go AST and removes imports that are no longer
// referenced by active code after types have been commented out.
func dropUnusedImports(filename string, content []byte) ([]byte, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, filename, content, parser.ParseComments)
	if err != nil {
		return nil, fmt.Errorf("parsing: %w", err)
	}

	changed := false
	for _, imp := range unusedImports(file) {
		if astutil.DeleteNamedImport(fset, file, imp.name, imp.path) {
			changed = true
			klog.Infof("Dropped now-unused import %q from %s", imp.path, filename)
		}
	}
	if !changed {
		return content, nil
	}

	var buf bytes.Buffer
	if err := format.Node(&buf, fset, file); err != nil {
		return nil, fmt.Errorf("formatting: %w", err)
	}
	return buf.Bytes(), nil
}

// importRef names an import the way astutil.DeleteNamedImport expects: the
// alias, or "" for none, and the unquoted path.
type importRef struct{ name, path string }

// unusedImports returns all imports in file that are not referenced by any selector expression.
// It collects all unused imports before deleting to avoid mutating file.Imports while iterating.
func unusedImports(file *ast.File) []importRef {
	used := selectorQualifiers(file)
	var unused []importRef
	for _, imp := range file.Imports {
		ref, qualifier, ok := importQualifier(imp)
		if ok && !used[qualifier] {
			unused = append(unused, ref)
		}
	}
	return unused
}

// selectorQualifiers returns every identifier used on the left of a selector,
// such as krm in krm.Bar. Comment text is never parsed into expressions, so a
// commented-out type contributes nothing. A local variable that shares a name
// with an import keeps that import, which errs on the side of keeping.
func selectorQualifiers(file *ast.File) map[string]bool {
	used := make(map[string]bool)
	ast.Inspect(file, func(n ast.Node) bool {
		if sel, ok := n.(*ast.SelectorExpr); ok {
			if ident, ok := sel.X.(*ast.Ident); ok {
				used[ident.Name] = true
			}
		}
		return true
	})
	return used
}

// importQualifier returns the identifier a file uses to refer to an import,
// and reports false for imports that cannot be safely pruned (such as blank imports,
// dot imports, or non-standard package paths).
func importQualifier(imp *ast.ImportSpec) (ref importRef, qualifier string, ok bool) {
	if imp == nil || imp.Path == nil {
		return importRef{}, "", false
	}
	path, err := strconv.Unquote(imp.Path.Value)
	if err != nil {
		return importRef{}, "", false
	}
	ref = importRef{path: path}
	if imp.Name != nil {
		ref.name = imp.Name.Name
	}
	switch ref.name {
	case "_", ".":
		return ref, "", false
	case "":
		qualifier = path[strings.LastIndex(path, "/")+1:]
		if !token.IsIdentifier(qualifier) || isMajorVersion(qualifier) {
			return ref, "", false
		}
		return ref, qualifier, true
	default:
		return ref, ref.name, true
	}
}

// isMajorVersion reports whether a path segment is a module major-version
// suffix such as v2, which is never the package name.
func isMajorVersion(s string) bool {
	return len(s) > 1 && s[0] == 'v' && strings.TrimLeft(s[1:], "0123456789") == ""
}
