type GenerateCRDOptions struct {
	*options.GenerateOptions

	ServiceName string

	OutputAPIDirectory string
	SkipScaffoldFiles  bool

	Resources options.ResourceList

	PruneUnusedTypes bool

	// PrepopulateSpec populates <Kind>Spec and <Kind>ObservedState with fields
	// derived from the resource proto message definition.
	PrepopulateSpec bool
	EmitParentRefs  bool
}

func (o *GenerateCRDOptions) InitDefaults() error {
	root, err := options.RepoRoot()
	if err != nil {
		return err
	}
	o.OutputAPIDirectory = root + "/apis/"
	o.PruneUnusedTypes = true
	return nil
}

func (o *GenerateCRDOptions) BindFlags(cmd *cobra.Command) {
	cmd.Flags().StringVarP(&o.ServiceName, "service", "s", o.ServiceName, "the GCP service name")

	cmd.Flags().StringVar(&o.OutputAPIDirectory, "output-api", o.OutputAPIDirectory, "base directory for writing APIs")
	cmd.Flags().Var(&o.Resources, "resource", "the KRM Kind and the equivalent proto resource separated with a colon.  e.g. for resource google.storage.v1.Bucket, the flag should be `StorageBucket:Bucket`.  Can be specified multiple times.")
	cmd.Flags().BoolVar(&o.SkipScaffoldFiles, "skip-scaffold-files", false, "skip generating scaffold files (types, refs, and identity) for all resources generated by this command")
	cmd.Flags().BoolVar(&o.PruneUnusedTypes, "prune-unused-types", o.PruneUnusedTypes, "prune unreachable types from generated files")
	cmd.Flags().BoolVar(&o.PrepopulateSpec, "prepopulate-spec", false, "fill the scaffolded Spec and ObservedState from the proto message instead of emitting a three-field stub, and record what still needs a human in apis/<service>/needs_judgement_call.txt. Opt in one service at a time")
	cmd.Flags().BoolVar(&o.EmitRequiredFromProto, "emit-required-from-proto", false, "emit // +required markers for fields marked REQUIRED in proto. Opt-in per service to avoid breaking CRD schema changes on existing resources")
	cmd.Flags().BoolVar(&o.EmitParentRefs, "emit-parent-refs", false, "emit one spec field referencing the resource's direct parent, where google.api.resource declares a parent below project and location and a reference type for it already exists. Each field is marked +kcc:guess and recorded in apis/<service>/needs_judgement_call.txt, and a parent with no reference type is recorded there rather than guessed. Opt in one service at a time: it adds a field to the CRD of a resource people already use")
}

func BuildCommand(baseOptions *options.GenerateOptions) *cobra.Command {
	opt := &GenerateCRDOptions{
		GenerateOptions: baseOptions,
	}

	if err := opt.InitDefaults(); err != nil {
		fmt.Fprintf(os.Stderr, "Error initializing defaults: %v\n", err)
		os.Exit(1)
	}

	cmd := &cobra.Command{
		Use:   "generate-types",
		Short: "generate KRM types for a proto service",
		PreRunE: func(cmd *cobra.Command, args []string) error {
			if err := opt.loadAndApplyConfig(); err != nil {
				return err
			}
			return opt.validate()
		},
		RunE: func(cmd *cobra.Command, args []string) error {
			ctx := cmd.Context()
			if err := RunGenerateCRD(ctx, opt); err != nil {
				return err
			}
			return nil
		},
	}

	opt.BindFlags(cmd)

	return cmd
}

func RunGenerateCRD(ctx context.Context, o *GenerateCRDOptions) error {
	log := klog.FromContext(ctx)

	gv, err := schema.ParseGroupVersion(o.APIVersion)
	if err != nil {
		return fmt.Errorf("APIVersion %q is not valid: %w", o.APIVersion, err)
	}

	api, err := protoapi.LoadProto(o.GenerateOptions.ProtoSourcePath, o.GenerateOptions.ProtoOverlayPath)
	if err != nil {
		return fmt.Errorf("loading proto: %w", err)
	}

	goPackage := strings.TrimSuffix(gv.Group, ".cnrm.cloud.google.com") + "/" + gv.Version

	scaffolder := &scaffold.APIScaffolder{
		BaseDir:         o.OutputAPIDirectory,
		GoPackage:       goPackage,
		Group:           gv.Group,
		Version:         gv.Version,
		PackageProtoTag: o.ServiceName,
		// Without the proto the scaffolder has no google.api.resource to read, so
		// ResourcePattern is empty and there is no parent to name.
		Proto:          api,
		EmitParentRefs: o.EmitParentRefs,
	}
	if scaffolder.DocFileNotExist() {
		if err := scaffolder.AddDocFile(); err != nil {
			return fmt.Errorf("add doc.go file: %w", err)
		}
	}
	if scaffolder.GroupVersionFileNotExist() {
		if err := scaffolder.AddGroupVersionFile(); err != nil {
			return fmt.Errorf("add groupversion_info.go file: %w", err)
		}
	}

	writeOptions := codegen.WriteOptions{
		EmitRequired:  o.EmitRequiredFromProto,
		Prepopulating: o.PrepopulateSpec,
	}

	typeGenerator := codegen.NewTypeGenerator(goPackage, o.OutputAPIDirectory, api)
	typeGenerator.WithIncludeSkippedOutput(o.GenerateOptions.IncludeSkippedOutput)
	typeGenerator.WithWriteOptions(writeOptions)
	// Reserve Kind type names to prevent the type generator from duplicating
	// definitions that will be emitted by the scaffolder in subsequent steps
	// (particularly during fresh scaffoldings where files do not exist on disk yet).
	for _, resource := range o.Resources {
		typeGenerator.WithReservedTypeNames(resource.Kind)
		if o.PrepopulateSpec {
			typeGenerator.WithReservedTypeNames(resource.Kind + "ObservedState")
		}
	}

	// Accumulate judgement items across all resources in this run so the queue file
	// is written atomically once at the end.
	var judgement []string

	resourceAnnotations := make([]string, 0, len(o.Resources))
	for _, resource := range o.Resources {
		resourceProtoFullName := resolveProtoFullName(api, o.ServiceName, resource)
		log.V(2).Info("visiting proto", "name", resourceProtoFullName)
		if err := typeGenerator.VisitProto(resourceProtoFullName); err != nil {
			return err
		}
		resourceAnnotations = append(resourceAnnotations, fmt.Sprintf("%s:%s", resource.Kind, resource.ProtoName))
	}

	generatedFileAnnotation := &annotations.FileAnnotation{
		Key: "+generated:types",
		Attributes: map[string][]string{
			"proto.service": {o.ServiceName},
			"krm.group":     {gv.Group},
			"krm.version":   {gv.Version},
			"resource":      resourceAnnotations,
		},
	}
	typeGenerator = typeGenerator.WithGeneratedFileAnnotation(generatedFileAnnotation)

	if err := typeGenerator.WriteVisitedMessages(); err != nil {
		return err
	}

	if err := typeGenerator.WriteOutputMessages(); err != nil {
		return err
	}

	for _, resource := range o.Resources { // A separate loop is needed to scaffold files AFTER all the visited messages have been generated.
		skipScaffold := o.SkipScaffoldFiles || resource.SkipScaffoldFiles
		if skipScaffold {
			log.Info("skipping scaffolding type, refs and identity files", "resource", resource.ProtoName)
		} else {
			if scaffolder.TypeFileExists(resource) {
				klog.V(1).Infof("file %s already exists, skipping\n", scaffolder.PathToTypeFile(resource))
			} else {
				var prepopulated *scaffold.PrepopulateResult
				if o.PrepopulateSpec {
					msg, err := resourceMessage(api, o.ServiceName, resource)
					if err != nil {
						return err
					}
					prepopulated, err = scaffold.PrepopulateSpec(msg, writeOptions)
					if err != nil {
						return fmt.Errorf("prepopulating spec for %s: %w", resource.Kind, err)
					}
					// Populate ObservedState using output fields discovered during proto traversal.
					if details, ok := typeGenerator.OutputFieldsFor(string(msg.FullName())); ok {
						var obsJudgement []scaffold.JudgementItem
						prepopulated.ObservedStateFields, obsJudgement =
							scaffold.PrepopulateObservedState(details, typeGenerator.ObservedStateMessages(), writeOptions)
						prepopulated.Judgement = append(prepopulated.Judgement, obsJudgement...)
					}
					// The template writes the ObservedState struct whether or not
					// it has fields, so an empty body is the only signal there is.
					// Reading the body rather than the proto's annotations also
					// catches a resource whose output fields were all dropped, as
					// identity fields or as types the generator cannot write.
					//
					// A CRD with an empty status.observedState fails
					// TestCRDObjectTypes, which rejects an object type with no
					// properties; the ones that exist today sit in its
					// knownInvalidCRDs allowlist. This entry names the resource as
					// it is generated, so the gap reaches a person before it
					// reaches that allowlist.
					if prepopulated.ObservedStateFields == "" {
						prepopulated.Judgement = append(prepopulated.Judgement, scaffold.JudgementItem{
							Reason: "empty-observedstate",
							Detail: "nothing was generated into status.observedState; the proto " +
								"probably marks no field OUTPUT_ONLY, so output fields landed " +
								"in the Spec. Decide what belongs in status",
						})
					}
					prepopulated.ExtraImports = scaffold.ExtraImportsFor(prepopulated.SpecFields, prepopulated.ObservedStateFields)
					judgement = append(judgement, scaffold.FormatJudgementEntries(resource.Kind, gv.Group, prepopulated.Judgement))
				}
				if err := scaffolder.AddTypeFile(resource, prepopulated); err != nil {
					return fmt.Errorf("add type file %s: %w", scaffolder.PathToTypeFile(resource), err)
				}
			}
		}
	}

	if o.PrepopulateSpec {
		// Record fields that could not be mapped to Go types. Since nested messages
		// may be shared across multiple resources, these are listed as informational
		// comments at the service level rather than as resource-specific queue items.
		if u := typeGenerator.UnsupportedFields(); len(u) > 0 {
			var b strings.Builder
			b.WriteString("\n# Fields dropped because the generator could not produce a Go type for\n")
			b.WriteString("# them. Because nested messages may be shared across resources, they are\n")
			b.WriteString("# listed per service as comments.\n")
			for _, f := range u {
				fmt.Fprintf(&b, "# dropped: %s.%s reason=%s\n", f.Message, f.Field, f.Reason)
			}
			judgement = append(judgement, b.String())
		}
	}

	if o.PrepopulateSpec || len(judgement) > 0 {
		if err := writeJudgementQueue(o.OutputAPIDirectory, goPackage, judgement); err != nil {
			return fmt.Errorf("writing judgement queue: %w", err)
		}
	}

	addCopyright := true
	writeEmptyFiles := true
	if err := typeGenerator.WriteFiles(addCopyright, writeEmptyFiles); err != nil {
		return err
	}

	if o.PruneUnusedTypes {
		pruneOpt := &prunetypes.PruneTypesOptions{
			GenerateOptions: o.GenerateOptions,
			Target:          filepath.Join(o.OutputAPIDirectory, goPackage),
		}
		if err := prunetypes.PruneTypes(ctx, pruneOpt); err != nil {
			return fmt.Errorf("pruning unreachable types: %w", err)
		}
	}

	return nil
}

func (o *GenerateCRDOptions) loadAndApplyConfig() error {
	if o.ConfigFilePath == "" {
		return nil
	}
	config, err := codegen.LoadConfig(o.ConfigFilePath)
	if err != nil {
		return fmt.Errorf("loading service config: %w", err)
	}
	if config == nil {
		return nil
	}

	o.ServiceName = config.Service
	o.APIVersion = config.APIVersion
	if o.ProtoOverlayPath == "" && config.ProtoOverlay != "" {
		if filepath.IsAbs(config.ProtoOverlay) {
			o.ProtoOverlayPath = config.ProtoOverlay
		} else {
			o.ProtoOverlayPath = filepath.Join(filepath.Dir(o.ConfigFilePath), config.ProtoOverlay)
		}
	}
	for _, res := range config.Resources {
		o.Resources = append(o.Resources, options.Resource{
			Kind:              res.Kind,
			ProtoName:         res.ProtoName,
			SkipScaffoldFiles: res.SkipScaffoldFiles,
		})
	}
	return nil
}

func (o *GenerateCRDOptions) validate() error {
	if o.ServiceName == "" {
		return fmt.Errorf("`--service` is required")
	}
	if o.GenerateOptions.ProtoSourcePath == "" {
		return fmt.Errorf("`--proto-source-path` is required")
	}
	if len(o.Resources) == 0 {
		return fmt.Errorf("`--resource` is required")
	}
	return nil
}

// resolveProtoFullName maps a --resource entry to a fully qualified proto message
// name, trying each comma-separated service in turn.
func resolveProtoFullName(api *protoapi.Proto, serviceName string, resource options.Resource) string {
	if strings.Contains(resource.ProtoName, ".") {
		return resource.ProtoName
	}
	for _, svc := range strings.Split(serviceName, ",") {
		candidate := svc + "." + resource.ProtoName
		if _, err := api.Files().FindDescriptorByName(protoreflect.FullName(candidate)); err == nil {
			return candidate
		}
	}
	// Nothing matched, so fall back to the first service and let the caller's
	// lookup produce the error with the full name in it.
	return strings.Split(serviceName, ",")[0] + "." + resource.ProtoName
}

// resourceMessage looks up the descriptor for a --resource entry.
func resourceMessage(api *protoapi.Proto, serviceName string, resource options.Resource) (protoreflect.MessageDescriptor, error) {
	fullName := resolveProtoFullName(api, serviceName, resource)
	d, err := api.Files().FindDescriptorByName(protoreflect.FullName(fullName))
	if err != nil {
		return nil, fmt.Errorf("finding proto message %s: %w", fullName, err)
	}
	msg, ok := d.(protoreflect.MessageDescriptor)
	if !ok {
		return nil, fmt.Errorf("%s is not a message", fullName)
	}
	return msg, nil
}

// writeJudgementQueue writes items requiring human review (e.g. potential reference
// fields or naming decisions) to needs_judgement_call.txt in the service root.
func writeJudgementQueue(apiDir, goPackage string, entries []string) error {
	var body strings.Builder
	for _, e := range entries {
		body.WriteString(e)
	}
	if body.Len() == 0 {
		return nil
	}

	// The queue is placed at apis/<service>/needs_judgement_call.txt (above the version directory)
	// to track review items across all versions for the service.
	serviceDir := filepath.Dir(filepath.Join(apiDir, goPackage))
	path := filepath.Join(serviceDir, "needs_judgement_call.txt")

	header := "# Fields emitted during generation that require human review (e.g., potential\n" +
		"# references, field omissions, or KRM naming conventions).\n" +
		"#\n" +
		"# While a resource has active entries here, TestMissingRefs suppresses [refs]\n" +
		"# validation failures. Resolving all entries enables full reference checking.\n" +
		"\n"

	if err := os.MkdirAll(serviceDir, 0755); err != nil {
		return err
	}

	// Merge rather than truncate. The queue is per service but generate.sh calls
	// generate-types once per proto version, discoveryengine twice,
	// networksecurity three times and dialogflow four, and writing the file
	// outright meant the last call silently discarded every earlier call's
	// entries. That left 34 fields carrying a +kcc:guess marker in the types file
	// with nothing about them in the queue.
	merged := mergeQueueLines(header, readFileOrEmpty(path), body.String())
	return os.WriteFile(path, []byte(header+strings.Join(merged, "\n")+"\n"), 0644)
}

// mergeQueueLines returns the queue's lines without its header: every line of
// existing first, so a hand-edited queue keeps its order, then each line of
// added that existing does not already have. Lines are compared whole, so
// merging the same entries again changes nothing. Blank lines are dropped.
//
// Only the header's own lines are removed from existing, because the header is
// rewritten on every call. Other comment lines stay: findings that cannot be
// attributed to a single Kind are written as comments precisely so they do not
// suppress [refs], and dropping every "#" line kept only the last invocation's.
// compute kept 6 of its 56 sibling matches that way, and backupdr none of its
// 2.
func mergeQueueLines(header, existing, added string) []string {
	isHeader := map[string]bool{}
	for _, line := range strings.Split(header, "\n") {
		isHeader[line] = true
	}
	seen := map[string]bool{}
	var out []string
	keep := func(line string) {
		if line != "" && !seen[line] {
			seen[line] = true
			out = append(out, line)
		}
	}
	for _, line := range strings.Split(existing, "\n") {
		if !isHeader[line] {
			keep(line)
		}
	}
	for _, line := range strings.Split(added, "\n") {
		keep(line)
	}
	return out
}

// readFileOrEmpty returns the file's contents, or "" if it cannot be read. A
// queue that does not exist yet is the normal first-run case.
func readFileOrEmpty(path string) string {
	b, err := os.ReadFile(path)
	if err != nil {
		return ""
	}
	return string(b)
}
