type GenerateCRDOptions struct {
	*options.GenerateOptions

	ServiceName string

	OutputAPIDirectory string
	SkipScaffoldFiles  bool

	Resources options.ResourceList

	PruneUnusedTypes bool

	EmitRequiredFromProto bool
	// PrepopulateSpec populates <Kind>Spec and <Kind>ObservedState with fields
	// derived from the resource proto message definition.
	PrepopulateSpec      bool
	DetectOutputOnly     bool
	EmitPluralAcronyms   bool
	EmitMessageMaps      bool
	EmitParentRefs       bool
	EmitSiblingRefs      bool
	EmitReferenceHints   bool
	PlaceServerSetFields bool
	EmitSourceLinks      bool
}

func (o *GenerateCRDOptions) InitDefaults() error {
	root, err := options.RepoRoot()
	if err != nil {
		return err
	}
	o.OutputAPIDirectory = root + "/apis/"
	o.PruneUnusedTypes = true
	return nil
}

func (o *GenerateCRDOptions) BindFlags(cmd *cobra.Command) {
	cmd.Flags().StringVarP(&o.ServiceName, "service", "s", o.ServiceName, "the GCP service name")

	cmd.Flags().StringVar(&o.OutputAPIDirectory, "output-api", o.OutputAPIDirectory, "base directory for writing APIs")
	cmd.Flags().Var(&o.Resources, "resource", "the KRM Kind and the equivalent proto resource separated with a colon.  e.g. for resource google.storage.v1.Bucket, the flag should be `StorageBucket:Bucket`.  Can be specified multiple times.")
	cmd.Flags().BoolVar(&o.SkipScaffoldFiles, "skip-scaffold-files", false, "skip generating scaffold files (types, refs, and identity) for all resources generated by this command")
	cmd.Flags().BoolVar(&o.PruneUnusedTypes, "prune-unused-types", o.PruneUnusedTypes, "prune unreachable types from generated files")
	cmd.Flags().BoolVar(&o.PrepopulateSpec, "prepopulate-spec", false, "fill the scaffolded Spec and ObservedState from the proto message instead of emitting a three-field stub, and record what still needs a human in apis/<service>/judgement_queue.yaml. Opt in one service at a time")
	cmd.Flags().BoolVar(&o.EmitPluralAcronyms, "emit-plural-acronyms", false, "case plural acronyms as KRM conventions want, so related_uris becomes relatedURIs rather than relatedUris. Opt in one service at a time: it renames fields, which is a breaking change for a resource people already use")
	cmd.Flags().BoolVar(&o.EmitMessageMaps, "emit-message-maps", false, "generate map<string, Message> fields as a map of the value's Go type instead of leaving them out. Opt in one service at a time: it adds fields to the CRD of a resource people already use, and generate-mapper needs the same flag")
	cmd.Flags().BoolVar(&o.DetectOutputOnly, "detect-output-only-in-comments", false, "record a spec field whose proto comment says \"Output only.\" or \"[Output Only]\" but that carries no field_behavior annotation, in apis/<service>/judgement_queue.yaml. Requires --prepopulate-spec. Reports only: moving the field is a hand edit")
	cmd.Flags().BoolVar(&o.PlaceServerSetFields, "place-server-set-fields", false, "put a small allowlist of server-computed fields (createTime, uid, selfLink, etag and a few more) into ObservedState when the proto carries no field_behavior anywhere, instead of leaving them in the Spec for a user to set. Requires --prepopulate-spec. Each one is also recorded in apis/<service>/judgement_queue.yaml. Opt in one service at a time: it moves fields between spec and status, which is a breaking change for a resource people already use")
	cmd.Flags().BoolVar(&o.EmitRequiredFromProto, "emit-required-from-proto", false, "emit // +required markers for fields marked REQUIRED in proto. Opt-in per service to avoid breaking CRD schema changes on existing resources")
	cmd.Flags().BoolVar(&o.EmitParentRefs, "emit-parent-refs", false, "emit one spec field referencing the resource's direct parent, where google.api.resource declares a parent below project and location and a reference type for it already exists. Requires --prepopulate-spec. Each field is marked +kcc:guess and recorded in apis/<service>/judgement_queue.yaml, and a parent with no reference type is recorded there rather than guessed. Opt in one service at a time: it adds a field to the CRD of a resource people already use")
	cmd.Flags().BoolVar(&o.EmitSiblingRefs, "emit-sibling-refs", false, "mark a string field whose name matches a resource this service declares as a probable reference to it, with a +kcc:guess comment and an entry in apis/<service>/judgement_queue.yaml. The field stays a string: this reports a candidate rather than generating a reference. Opt in one service at a time, though controller-gen strips the comment, so this cannot change a CRD")
	cmd.Flags().BoolVar(&o.EmitSourceLinks, "emit-source-links", false, "write links to the resource's proto, its service docs and its REST reference page as +kcc:source markers at the top of a new <kind>_types.go. The docs links are guessed and checked online in the same run; a link that does not check out is still written, marked +kcc:guess and recorded in apis/<service>/judgement_queue.yaml. Only a newly scaffolded types file gets links, so existing resources do not change")
	cmd.Flags().BoolVar(&o.EmitReferenceHints, "emit-reference-hints", false, "record a spec field, at any depth, whose description or name suggests it points at another resource, in apis/<service>/judgement_queue.yaml. Uses the rules TestMissingRefs applies, plus looser description and name rules that only hint. A field those rules say KCC cannot express as a reference is recorded too, with the reason, and so is a field whose name ends in password. A nested field with a google.api.resource_reference annotation is recorded the way --prepopulate-spec records a top-level one. Requires --prepopulate-spec. Reports only: the field is still generated as a string")
}

func BuildCommand(baseOptions *options.GenerateOptions) *cobra.Command {
	opt := &GenerateCRDOptions{
		GenerateOptions: baseOptions,
	}

	if err := opt.InitDefaults(); err != nil {
		fmt.Fprintf(os.Stderr, "Error initializing defaults: %v\n", err)
		os.Exit(1)
	}

	cmd := &cobra.Command{
		Use:   "generate-types",
		Short: "generate KRM types for a proto service",
		PreRunE: func(cmd *cobra.Command, args []string) error {
			if err := opt.loadAndApplyConfig(); err != nil {
				return err
			}
			return opt.validate()
		},
		RunE: func(cmd *cobra.Command, args []string) error {
			ctx := cmd.Context()
			if err := RunGenerateCRD(ctx, opt); err != nil {
				return err
			}
			return nil
		},
	}

	opt.BindFlags(cmd)

	return cmd
}

func RunGenerateCRD(ctx context.Context, o *GenerateCRDOptions) error {
	log := klog.FromContext(ctx)

	gv, err := schema.ParseGroupVersion(o.APIVersion)
	if err != nil {
		return fmt.Errorf("APIVersion %q is not valid: %w", o.APIVersion, err)
	}

	api, err := protoapi.LoadProto(o.GenerateOptions.ProtoSourcePath, o.GenerateOptions.ProtoOverlayPath)
	if err != nil {
		return fmt.Errorf("loading proto: %w", err)
	}

	goPackage := strings.TrimSuffix(gv.Group, ".cnrm.cloud.google.com") + "/" + gv.Version

	scaffolder := &scaffold.APIScaffolder{
		BaseDir:         o.OutputAPIDirectory,
		GoPackage:       goPackage,
		Group:           gv.Group,
		Version:         gv.Version,
		PackageProtoTag: o.ServiceName,
		// Without the proto the scaffolder has no google.api.resource to read, so
		// ResourcePattern is empty and there is no parent to name.
		Proto:          api,
		EmitParentRefs: o.EmitParentRefs,
	}
	if scaffolder.DocFileNotExist() {
		if err := scaffolder.AddDocFile(); err != nil {
			return fmt.Errorf("add doc.go file: %w", err)
		}
	}
	if scaffolder.GroupVersionFileNotExist() {
		if err := scaffolder.AddGroupVersionFile(); err != nil {
			return fmt.Errorf("add groupversion_info.go file: %w", err)
		}
	}

	// For --emit-sibling-refs, collect the Kinds in this run and those already
	// in the package. A string field named after one of them is flagged as a
	// possible reference. Both WriteVisitedMessages and PrepopulateSpec read
	// the map, so it goes into writeOptions before either runs.
	var siblings map[string]string
	if o.EmitSiblingRefs {
		var thisRun []string
		for _, resource := range o.Resources {
			thisRun = append(thisRun, resource.Kind)
		}
		siblings = codegen.SiblingKinds(
			filepath.Join(o.OutputAPIDirectory, goPackage),
			strings.TrimSuffix(gv.Group, ".cnrm.cloud.google.com"),
			thisRun...)
	}

	writeOptions := codegen.WriteOptions{
		EmitRequired:         o.EmitRequiredFromProto,
		Prepopulating:        o.PrepopulateSpec,
		EmitPluralAcronyms:   o.EmitPluralAcronyms,
		EmitMessageMaps:      o.EmitMessageMaps,
		Siblings:             siblings,
		PlaceServerSetFields: o.PlaceServerSetFields,
	}

	typeGenerator := codegen.NewTypeGenerator(goPackage, o.OutputAPIDirectory, api)
	typeGenerator.WithIncludeSkippedOutput(o.GenerateOptions.IncludeSkippedOutput)
	typeGenerator.WithWriteOptions(writeOptions)
	// Reserve Kind type names to prevent the type generator from duplicating
	// definitions that will be emitted by the scaffolder in subsequent steps
	// (particularly during fresh scaffoldings where files do not exist on disk yet).
	for _, resource := range o.Resources {
		typeGenerator.WithReservedTypeNames(resource.Kind)
		if o.PrepopulateSpec {
			typeGenerator.WithReservedTypeNames(resource.Kind + "ObservedState")
		}
	}

	// Accumulate queue entries across all resources in this run so the queue
	// file is written once at the end.
	var queued []judgement.Entry

	var linkResolver *sourcelinks.Resolver
	if o.EmitSourceLinks {
		root, err := options.RepoRoot()
		if err != nil {
			return err
		}
		linkResolver, err = sourcelinks.NewResolver(root)
		if err != nil {
			return fmt.Errorf("setting up --emit-source-links: %w", err)
		}
	}

	// Each --resource is resolved once here, so the warning is logged once and
	// the scaffolding below uses the same message.
	protoFullNames := make(map[string]string, len(o.Resources))
	resourceAnnotations := make([]string, 0, len(o.Resources))
	for _, resource := range o.Resources {
		resourceProtoFullName, matches := resolveProtoFullName(api, o.ServiceName, resource)
		protoFullNames[resource.Kind] = resourceProtoFullName
		if item, ok := ambiguousResourceItem(resource, matches); ok {
			klog.Warningf("%s: %s", resource.Kind, item.Detail)
			if o.PrepopulateSpec {
				queued = append(queued, scaffold.JudgementEntries(resource.Kind, gv.Group, []scaffold.JudgementItem{item})...)
			}
		}
		log.V(2).Info("visiting proto", "name", resourceProtoFullName)
		if err := typeGenerator.VisitProto(resourceProtoFullName); err != nil {
			return err
		}
		resourceAnnotations = append(resourceAnnotations, fmt.Sprintf("%s:%s", resource.Kind, resource.ProtoName))
	}

	generatedFileAnnotation := &annotations.FileAnnotation{
		Key: "+generated:types",
		Attributes: map[string][]string{
			"proto.service": {o.ServiceName},
			"krm.group":     {gv.Group},
			"krm.version":   {gv.Version},
			"resource":      resourceAnnotations,
		},
	}
	typeGenerator = typeGenerator.WithGeneratedFileAnnotation(generatedFileAnnotation)

	if err := typeGenerator.WriteVisitedMessages(); err != nil {
		return err
	}

	if err := typeGenerator.WriteOutputMessages(); err != nil {
		return err
	}

	for _, resource := range o.Resources { // A separate loop is needed to scaffold files AFTER all the visited messages have been generated.
		skipScaffold := o.SkipScaffoldFiles || resource.SkipScaffoldFiles
		if skipScaffold {
			log.Info("skipping scaffolding type, refs and identity files", "resource", resource.ProtoName)
		} else {
			if scaffolder.TypeFileExists(resource) {
				klog.V(1).Infof("file %s already exists, skipping\n", scaffolder.PathToTypeFile(resource))
			} else {
				var prepopulated *scaffold.PrepopulateResult
				if o.PrepopulateSpec {
					msg, err := resourceMessage(api, protoFullNames[resource.Kind])
					if err != nil {
						return err
					}
					prepopulated, err = scaffold.PrepopulateSpec(msg, writeOptions)
					if err != nil {
						return fmt.Errorf("prepopulating spec for %s: %w", resource.Kind, err)
					}
					if o.EmitReferenceHints {
						prepopulated.Judgement = append(prepopulated.Judgement, scaffold.ReferenceHints(msg, writeOptions)...)
					}
					// Populate ObservedState using output fields discovered during proto traversal.
					if details, ok := typeGenerator.OutputFieldsFor(string(msg.FullName())); ok {
						var obsJudgement []scaffold.JudgementItem
						prepopulated.ObservedStateFields, obsJudgement =
							scaffold.PrepopulateObservedState(details, typeGenerator.ObservedStateMessages(), writeOptions)
						prepopulated.Judgement = append(prepopulated.Judgement, obsJudgement...)
					}
					// The template writes the ObservedState struct whether or not
					// it has fields, so an empty body is the only signal there is.
					// Reading the body rather than the proto's annotations also
					// catches a resource whose output fields were all dropped, as
					// identity fields or as types the generator cannot write.
					//
					// A CRD with an empty status.observedState fails
					// TestCRDObjectTypes, which rejects an object type with no
					// properties; the ones that exist today sit in its
					// knownInvalidCRDs allowlist. This entry names the resource as
					// it is generated, so the gap reaches a person before it
					// reaches that allowlist.
					if prepopulated.ObservedStateFields == "" {
						prepopulated.Judgement = append(prepopulated.Judgement, scaffold.JudgementItem{
							Reason: "empty-observedstate",
							Detail: "nothing was generated into status.observedState; the proto " +
								"probably marks no field OUTPUT_ONLY, so output fields landed " +
								"in the Spec. Decide what belongs in status",
						})
					}
					if o.DetectOutputOnly {
						// Each candidate goes into the queue. The field sits in the
						// Spec and looks like any other generated field, so without
						// an entry nobody would notice it.
						for _, cand := range scaffold.DetectOutputOnlyInComments(msg, writeOptions) {
							// The entry names where the field belongs, not where
							// it currently sits. It accounts for a field absent
							// from ObservedState, so a path under .spec would
							// never line up with what is missing.
							prepopulated.Judgement = append(prepopulated.Judgement, scaffold.JudgementItem{
								FieldPath: ".status.observedState." + strings.TrimPrefix(cand.FieldPath, ".spec."),
								Reason:    "output-only-in-comment-only",
								Detail:    "proto comment says output only but no field_behavior annotation, so it was generated into the Spec instead. Move it if the comment is right: " + cand.Comment,
							})
						}
					}
					prepopulated.ExtraImports = scaffold.ExtraImportsFor(prepopulated.SpecFields, prepopulated.ObservedStateFields)
				}
				var sourceLinks string
				if linkResolver != nil {
					var linkEntries []judgement.Entry
					sourceLinks, linkEntries, err = resolveSourceLinks(ctx, linkResolver, api, resource.Kind, gv.Group, protoFullNames[resource.Kind])
					if err != nil {
						return err
					}
					queued = append(queued, linkEntries...)
				}
				if err := scaffolder.AddTypeFile(resource, prepopulated, sourceLinks); err != nil {
					return fmt.Errorf("add type file %s: %w", scaffolder.PathToTypeFile(resource), err)
				}
				// This runs after AddTypeFile, which is where decisions that
				// depend on the parent shape are recorded.
				if prepopulated != nil {
					queued = append(queued, scaffold.JudgementEntries(resource.Kind, gv.Group, prepopulated.Judgement)...)
				}
			}
		}
	}

	// The findings below are in nested messages, which several resources can
	// share. They are recorded against the proto message rather than a Kind.
	if o.PrepopulateSpec {
		// Fields the generator could not produce a Go type for.
		for _, f := range typeGenerator.UnsupportedFields() {
			queued = append(queued, judgement.Entry{
				ProtoMessage: f.Message,
				Field:        f.Field,
				Reason:       "unsupported-field-type",
				Detail:       f.Reason,
				Status:       judgement.StatusOpen,
			})
		}
		for _, m := range typeGenerator.DerivedMessageMaps() {
			queued = append(queued, judgement.Entry{
				ProtoMessage: m.Message,
				Field:        m.Field,
				Reason:       "message-map-derived",
				Detail:       fmt.Sprintf("derived as map[string]%s from proto %s; verify Go type and mapping", m.GoType, m.ProtoType),
				Status:       judgement.StatusOpen,
			})
		}
	}
	// Each of these carries a +kcc:guess marker in types.generated.go.
	for _, f := range typeGenerator.SiblingGuesses() {
		queued = append(queued, judgement.Entry{
			ProtoMessage: f.Message,
			Field:        f.Field,
			Reason:       judgement.ReasonPossibleReferenceBySibling,
			Detail:       "the name matches " + f.Target + ", a resource this service declares; confirm whether it should be a reference",
			Status:       judgement.StatusOpen,
		})
	}

	if len(queued) > 0 {
		if err := writeJudgementQueue(o.OutputAPIDirectory, goPackage, queued); err != nil {
			return fmt.Errorf("writing judgement queue: %w", err)
		}
	}

	addCopyright := true
	writeEmptyFiles := true
	if err := typeGenerator.WriteFiles(addCopyright, writeEmptyFiles); err != nil {
		return err
	}

	if o.PruneUnusedTypes {
		pruneOpt := &prunetypes.PruneTypesOptions{
			GenerateOptions: o.GenerateOptions,
			Target:          filepath.Join(o.OutputAPIDirectory, goPackage),
		}
		if err := prunetypes.PruneTypes(ctx, pruneOpt); err != nil {
			return fmt.Errorf("pruning unreachable types: %w", err)
		}
	}

	return nil
}

func (o *GenerateCRDOptions) loadAndApplyConfig() error {
	if o.ConfigFilePath == "" {
		return nil
	}
	config, err := codegen.LoadConfig(o.ConfigFilePath)
	if err != nil {
		return fmt.Errorf("loading service config: %w", err)
	}
	if config == nil {
		return nil
	}

	o.ServiceName = config.Service
	o.APIVersion = config.APIVersion
	if o.ProtoOverlayPath == "" && config.ProtoOverlay != "" {
		if filepath.IsAbs(config.ProtoOverlay) {
			o.ProtoOverlayPath = config.ProtoOverlay
		} else {
			o.ProtoOverlayPath = filepath.Join(filepath.Dir(o.ConfigFilePath), config.ProtoOverlay)
		}
	}
	for _, res := range config.Resources {
		o.Resources = append(o.Resources, options.Resource{
			Kind:              res.Kind,
			ProtoName:         res.ProtoName,
			SkipScaffoldFiles: res.SkipScaffoldFiles,
		})
	}
	return nil
}

func (o *GenerateCRDOptions) validate() error {
	if o.ServiceName == "" {
		return fmt.Errorf("`--service` is required")
	}
	if o.GenerateOptions.ProtoSourcePath == "" {
		return fmt.Errorf("`--proto-source-path` is required")
	}
	if len(o.Resources) == 0 {
		return fmt.Errorf("`--resource` is required")
	}
	// Parent references are added to the prepopulated Spec, so on its own
	// the flag would do nothing.
	if o.EmitParentRefs && !o.PrepopulateSpec {
		return fmt.Errorf("`--emit-parent-refs` requires `--prepopulate-spec`")
	}
	// Reference hints are only collected while the Spec is prepopulated, so on
	// its own the flag would do nothing.
	if o.EmitReferenceHints && !o.PrepopulateSpec {
		return fmt.Errorf("`--emit-reference-hints` requires `--prepopulate-spec`")
	}
	// Output-only comments are only checked while the Spec is prepopulated, so
	// on its own the flag would do nothing.
	if o.DetectOutputOnly && !o.PrepopulateSpec {
		return fmt.Errorf("`--detect-output-only-in-comments` requires `--prepopulate-spec`")
	}
	// Server-set fields are only moved out of a prepopulated Spec. On its own
	// the flag would only add an unused ObservedState struct to
	// types.generated.go.
	if o.PlaceServerSetFields && !o.PrepopulateSpec {
		return fmt.Errorf("`--place-server-set-fields` requires `--prepopulate-spec`")
	}
	return nil
}

// resolveProtoFullName returns the fully qualified proto name for a --resource
// entry, and every service-qualified name that exists. A name that contains a
// dot is returned as is. Otherwise each comma-separated service is tried in
// order and the first match wins.
func resolveProtoFullName(api *protoapi.Proto, serviceName string, resource options.Resource) (string, []string) {
	if strings.Contains(resource.ProtoName, ".") {
		return resource.ProtoName, nil
	}
	// The same message name can exist in several of the listed services.
	// We return all matches so the caller can flag it when there is more than
	// one. We still use the first match, so the generated output does not
	// change.
	//
	// Example: notebooks lists v1 and v2, and both have an Instance message.
	// NotebookInstanceV2 was generated from v1 without any warning, and the
	// CRD ended up missing 39 fields.
	var matches []string
	for _, svc := range strings.Split(serviceName, ",") {
		candidate := svc + "." + resource.ProtoName
		if _, err := api.Files().FindDescriptorByName(protoreflect.FullName(candidate)); err == nil {
			matches = append(matches, candidate)
		}
	}
	if len(matches) > 0 {
		return matches[0], matches
	}
	// Nothing matched, so fall back to the first service and let the caller's
	// lookup produce the error with the full name in it.
	return strings.Split(serviceName, ",")[0] + "." + resource.ProtoName, nil
}

// ambiguousResourceItem returns a queue item when a --resource proto name
// matched more than one service. matches is what resolveProtoFullName
// returned, and the first entry is the one that was used.
//
// The warning alone scrolls past in generate.sh output. The queue is the file
// someone reviews, so the choice is recorded there too.
func ambiguousResourceItem(resource options.Resource, matches []string) (scaffold.JudgementItem, bool) {
	if len(matches) < 2 {
		return scaffold.JudgementItem{}, false
	}
	return scaffold.JudgementItem{
		Reason: "ambiguous-proto-name",
		Detail: fmt.Sprintf("%s exists in %d of the listed services (%s); generated from %s. "+
			"Put the full proto name in --resource to choose one",
			resource.ProtoName, len(matches), strings.Join(matches, ", "), matches[0]),
	}, true
}

// resourceMessage looks up the descriptor for a fully qualified proto name.
func resourceMessage(api *protoapi.Proto, fullName string) (protoreflect.MessageDescriptor, error) {
	d, err := api.Files().FindDescriptorByName(protoreflect.FullName(fullName))
	if err != nil {
		return nil, fmt.Errorf("finding proto message %s: %w", fullName, err)
	}
	msg, ok := d.(protoreflect.MessageDescriptor)
	if !ok {
		return nil, fmt.Errorf("%s is not a message", fullName)
	}
	return msg, nil
}

// resolveSourceLinks returns the source link block for a new types file, and
// an open queue entry for each link that did not verify. The network is only
// used to check the docs links; when it fails, the links are still written
// and queued, so generation never stops for it.
func resolveSourceLinks(ctx context.Context, r *sourcelinks.Resolver, api *protoapi.Proto, kind, group, fullName string) (string, []judgement.Entry, error) {
	msg, err := resourceMessage(api, fullName)
	if err != nil {
		return "", nil, err
	}
	var pattern string
	if md := protoapi.GetResourceMetadata(msg); md != nil {
		pattern = md.Pattern
	}
	links := r.Resolve(ctx, sourcelinks.Resource{Message: msg, Pattern: pattern, Files: api.Files()})
	var entries []judgement.Entry
	for _, l := range links {
		if l.Guess == "" {
			continue
		}
		klog.Warningf("%s: %s link not verified: %s", kind, l.Key, l.Detail)
		entries = append(entries, judgement.Entry{
			Kind:   kind,
			Group:  group,
			Reason: l.Guess,
			Detail: l.Detail,
			Status: judgement.StatusOpen,
		})
	}
	return sourcelinks.Render(kind, links), entries, nil
}

// writeJudgementQueue merges entries into apis/<service>/judgement_queue.yaml.
// The file sits above the version directory, so one queue covers every
// version of the service.
func writeJudgementQueue(apiDir, goPackage string, entries []judgement.Entry) error {
	serviceDir := filepath.Dir(filepath.Join(apiDir, goPackage))
	path := filepath.Join(serviceDir, judgement.FileName)

	if err := os.MkdirAll(serviceDir, 0755); err != nil {
		return err
	}

	// Merge rather than truncate. The queue is per service but generate.sh calls
	// generate-types once per proto version, discoveryengine twice,
	// networksecurity three times and dialogflow four, and writing the file
	// outright meant the last call silently discarded every earlier call's
	// entries. That left 34 fields carrying a +kcc:guess marker in the types file
	// with nothing about them in the queue.
	//
	// A file that does not parse is an error rather than something to
	// overwrite, because it may hold resolutions someone typed by hand.
	q, err := judgement.Read(path)
	if err != nil {
		return err
	}
	q.Merge(entries)
	return judgement.Write(path, q)
}
